/// **Осадный шагоход.** 9.0 × 12.0 × 8.0 м, том 36×48×32.
///
/// Четыре опоры и одно тяжёлое орудие: машина прорыва, вдвое выше
/// бота и вчетверо тяжелее танка.
pub fn siege_walker() -> UnitBody {
    let mut b = UnitBody::new_scaled(36, 48, 32, 4, MM);
    for &x0 in &[7i32, 29] {
        for &z0 in &[7i32, 25] {
            fill(
                &mut b,
                ((x0 - 4).max(0) as usize, (x0 + 4) as usize),
                (0, 3),
                ((z0 - 4).max(0) as usize, (z0 + 4) as usize),
                Part::Armour,
            );
            beam(&mut b, (x0, 3, z0), (x0, 14, z0), 6, 5, Part::Armour);
            let kx = if x0 < 18 { x0 + 3 } else { x0 - 3 };
            beam(&mut b, (x0, 14, z0), (kx, 23, z0), 6, 7, Part::Armour);
        }
    }
    // Корпус со скосом по носу.
    fill(&mut b, (2, 34), (22, 34), (2, 30), Part::Armour);
    fill(&mut b, (34, 36), (24, 31), (6, 26), Part::Armour);
    fill(&mut b, (3, 13), (24, 31), (6, 26), Part::Engine);
    // Башня, маска и ствол.
    fill(&mut b, (10, 28), (34, 42), (8, 24), Part::Armour);
    fill(&mut b, (20, 29), (35, 41), (12, 20), Part::Weapon);
    beam(&mut b, (28, 38, 16), (35, 38, 16), 6, 4, Part::Weapon);
    // Мачта. Ведётся от крыши корпуса, а не от высоты башни: первая
    // редакция начинала её на 42 и оставляла восемь вокселей пустоты
    // под ней — сенсор висел в воздухе и был отрезан от ядра.
    fill(&mut b, (6, 10), (34, 42), (14, 18), Part::Armour);
    fill(&mut b, (5, 11), (42, 48), (13, 19), Part::Sensor);
    fill(&mut b, (16, 20), (24, 28), (14, 18), Part::Core);
    seat(b, "осадный шагоход")
}

