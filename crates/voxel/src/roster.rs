/// **Экспериментальный паук.** 40 × 22 × 40 м, том 40×22×40, воксель метр.
///
/// В шесть с лишним раз длиннее танка. Восемь опор ставятся целочисленным
/// шагом: диагональ идёт короче на семь десятых, чтобы ноги ложились
/// кругом, а не квадратом.
pub fn spider() -> UnitBody {
    let mut b = UnitBody::new_scaled(40, 22, 40, 4, 1000);
    let c = (20usize, 20usize);
    // Восемь ног. Колено на четвёртом шаге, дальше вниз.
    const DIRS: [(i32, i32, i32); 8] = [
        (1, 0, 10),
        (-1, 0, 10),
        (0, 1, 10),
        (0, -1, 10),
        (1, 1, 7),
        (1, -1, 7),
        (-1, 1, 7),
        (-1, -1, 7),
    ];
    for (dx, dz, k) in DIRS {
        for t in 0..12i32 {
            let r = (8 + t) * k / 10;
            let (x, z) = (c.0 as i32 + dx * r, c.1 as i32 + dz * r);
            if x < 0 || z < 0 || x >= 40 || z >= 40 {
                continue;
            }
            let y = if t < 4 { 13 + t } else { (17 - (t - 4) * 2).max(0) };
            // Последний шаг — ступня до земли, иначе паук висит.
            let y0 = if t >= 10 { 0 } else { y };
            fill(
                &mut b,
                (x as usize, x as usize + 2),
                (y0 as usize, y as usize + 2),
                (z as usize, z as usize + 2),
                Part::Armour,
            );
        }
    }
    // Брюхо и купол корпуса: радиус тает с высотой.
    disc(&mut b, c, 10, (4, 6), Part::Armour);
    disc(&mut b, c, 12, (6, 12), Part::Armour);
    disc(&mut b, c, 9, (12, 15), Part::Armour);
    disc(&mut b, c, 6, (15, 18), Part::Armour);
    disc(&mut b, c, 6, (5, 9), Part::Engine);
    disc(&mut b, c, 4, (17, 19), Part::Sensor);
    // Лучевое орудие носом вперёд.
    fill(&mut b, (30, 40), (10, 14), (18, 22), Part::Weapon);
    fill(&mut b, (18, 22), (9, 13), (18, 22), Part::Core);
    seat(b, "экспериментальный паук")
}

/// **Мобильная крепость.** 56 × 16 × 26 м, том 56×16×26, воксель метр.
///
/// Девять танков в длину. Три башни на надстройке: у машины этого
/// класса одно орудие смотрелось бы как у танка, а разница классов
/// обязана читаться силуэтом.
pub fn fortress() -> UnitBody {
    let mut b = UnitBody::new_scaled(56, 16, 26, 4, 1000);
    // Гусеничные ленты.
    fill(&mut b, (2, 54), (0, 4), (0, 6), Part::Armour);
    fill(&mut b, (2, 54), (0, 4), (20, 26), Part::Armour);
    // Корпус и надстройка.
    fill(&mut b, (0, 56), (4, 10), (2, 24), Part::Armour);
    fill(&mut b, (10, 44), (10, 13), (5, 21), Part::Armour);
    fill(&mut b, (44, 54), (4, 10), (6, 20), Part::Engine);
    // Три башни со стволами.
    for x0 in [14usize, 24, 34] {
        fill(&mut b, (x0, x0 + 8), (13, 16), (9, 17), Part::Armour);
        fill(&mut b, (x0 + 5, x0 + 12), (14, 16), (12, 14), Part::Weapon);
    }
    // Мачта — от крыши корпуса, а не от высоты надстройки: надстройка
    // начинается только с x=10, и сенсор на носу висел бы в пустоте.
    fill(&mut b, (5, 9), (10, 13), (11, 15), Part::Armour);
    fill(&mut b, (5, 9), (13, 16), (11, 15), Part::Sensor);
    fill(&mut b, (26, 30), (5, 9), (11, 15), Part::Core);
    seat(b, "мобильная крепость")
}

/// Весь набор с именами — для отчёта и для тестов, чтобы новое тело
/// нельзя было добавить мимо проверок.
pub fn all() -> Vec<(&'static str, UnitBody)> {
    vec![
        ("танк", crate::unit::tank()),
        ("штурмовой бот", assault_bot()),
        ("осадный шагоход", siege_walker()),
        ("командная машина", commander()),
        ("экспериментальный паук", spider()),
        ("мобильная крепость", fortress()),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::topo::unit::CoreBufs;

    /// **У каждого тела есть ядро и все три подсистемы живы.**
    ///
    /// Это тот тест, ради которого набор и заведён: тело без ядра
    /// неубиваемо, тело с отрезанным от ядра орудием не стреляет,
    /// и оба случая молчат до самого боя.
    #[test]
    fn every_body_is_whole_and_armed() {
        let mut b = CoreBufs::default();
        for (name, body) in all() {
            let st = body.status(&mut b);
            assert!(st.alive, "{name}: ядро не живо");
            assert!(st.engine, "{name}: двигатель не связан с ядром");
            assert!(st.weapon, "{name}: орудие не связано с ядром");
            assert!(st.sensor, "{name}: сенсор не связан с ядром");
            assert_eq!(st.detached, 0, "{name}: вокселей в воздухе {}", st.detached);
        }
    }

    /// **Разброс размеров действительно есть.**
    ///
    /// Набор нужен ради разброса; если он схлопнется до одного класса,
    /// проверять станет нечего, и заметить это надо здесь.
    #[test]
    fn the_roster_actually_spans_a_range() {
        let sizes: Vec<u32> = all().iter().map(|(_, b)| b.extent_mm().0).collect();
        let (lo, hi) = (
            *sizes.iter().min().expect("набор пуст"),
            *sizes.iter().max().expect("набор пуст"),
        );
        assert!(lo <= 6_000, "самая мелкая машина {lo} мм — крупнее танка");
        assert!(hi >= 40_000, "самая крупная машина всего {hi} мм");
        assert!(hi / lo >= 8, "разброс всего {}x", hi / lo);
    }

    /// **Масштаб воксела не меняет мирового объёма.**
    ///
    /// Главный инвариант ADR-178. Два одинаковых куба, собранные
    /// вокселем в 0.25 м и в 1 м, обязаны стоить экономике одинаково:
    /// «ресурс есть объём на плотность» (`CLAUDE.md`), а не число
    /// вокселей. Сломается — расхождение вылезет не сразу, а как
    /// перекос экономики между классами машин.
    #[test]
    fn the_same_block_costs_the_same_at_either_scale() {
        let mut fine = UnitBody::new_scaled(16, 16, 16, 2, 250);
        fill(&mut fine, (0, 16), (0, 16), (0, 16), Part::Armour);
        let mut coarse = UnitBody::new_scaled(4, 4, 4, 2, 1000);
        fill(&mut coarse, (0, 4), (0, 4), (0, 4), Part::Armour);
        assert_eq!(fine.extent_mm(), coarse.extent_mm(), "габариты разошлись");
        assert_eq!(
            fine.volume_mm3(),
            coarse.volume_mm3(),
            "тот же куб стоит разного: {} вокселей против {}",
            fine.solid_count(),
            coarse.solid_count()
        );
        assert_ne!(
            fine.solid_count(),
            coarse.solid_count(),
            "тест ничего не проверяет"
        );
    }

    /// **Крупное тело не помещалось в колонку `u32`.**
    ///
    /// Тот самый предел, ради которого колонка расширена (ADR-177):
    /// на тридцати двух битах крепость не собиралась вовсе.
    #[test]
    fn the_big_ones_need_more_than_thirty_two_columns() {
        let long = all().iter().filter(|(_, b)| b.vol.nx > 32).count();
        assert!(
            long > 0,
            "ни одно тело не длиннее 32 вокселей — предел не проверяется"
        );
    }
}
