/// **Штурмовой бот.** 4.0 × 7.0 × 4.0 м, том 16×28×16.
///
/// Двуногий, вдвое выше танка и вчетверо уже: силуэт обязан читаться
/// с той же высоты камеры, что и танк, иначе класс не различить.
pub fn assault_bot() -> UnitBody {
    let mut b = UnitBody::new_scaled(16, 28, 16, 3, MM);
    fill(&mut b, (2, 8), (0, 2), (4, 12), Part::Armour);
    fill(&mut b, (8, 14), (0, 2), (4, 12), Part::Armour);
    fill(&mut b, (3, 7), (2, 13), (5, 11), Part::Armour);
    fill(&mut b, (9, 13), (2, 13), (5, 11), Part::Armour);
    // Торс со скошенной грудью.
    fill(&mut b, (2, 14), (13, 24), (3, 13), Part::Armour);
    fill(&mut b, (1, 3), (15, 22), (4, 12), Part::Armour);
    // Руки-орудия по бокам.
    fill(&mut b, (0, 3), (16, 23), (5, 11), Part::Weapon);
    fill(&mut b, (13, 16), (16, 23), (5, 11), Part::Weapon);
    // Голова и сенсор в её лобовой части.
    fill(&mut b, (6, 10), (24, 28), (6, 10), Part::Armour);
    fill(&mut b, (6, 10), (25, 28), (4, 6), Part::Sensor);
    // Двигатель — ранец на спине.
    fill(&mut b, (4, 12), (14, 20), (11, 13), Part::Engine);
    fill(&mut b, (6, 9), (16, 19), (6, 9), Part::Core);
    seat(b, "штурмовой бот")
}

/// **Осадный шагоход.** 9.0 × 12.0 × 8.0 м, том 36×48×32.
///
/// Четыре опоры и одно тяжёлое орудие: машина прорыва, вдвое выше
/// бота и вчетверо тяжелее танка.
pub fn siege_walker() -> UnitBody {
    let mut b = UnitBody::new_scaled(36, 48, 32, 4, MM);
    for &x0 in &[7i32, 29] {
        for &z0 in &[7i32, 25] {
            fill(
                &mut b,
                ((x0 - 4).max(0) as usize, (x0 + 4) as usize),
                (0, 3),
                ((z0 - 4).max(0) as usize, (z0 + 4) as usize),
                Part::Armour,
            );
            beam(&mut b, (x0, 3, z0), (x0, 14, z0), 6, 5, Part::Armour);
            let kx = if x0 < 18 { x0 + 3 } else { x0 - 3 };
            beam(&mut b, (x0, 14, z0), (kx, 23, z0), 6, 7, Part::Armour);
        }
    }
    // Корпус со скосом по носу.
    fill(&mut b, (2, 34), (22, 34), (2, 30), Part::Armour);
    fill(&mut b, (34, 36), (24, 31), (6, 26), Part::Armour);
    fill(&mut b, (3, 13), (24, 31), (6, 26), Part::Engine);
    // Башня, маска и ствол.
    fill(&mut b, (10, 28), (34, 42), (8, 24), Part::Armour);
    fill(&mut b, (20, 29), (35, 41), (12, 20), Part::Weapon);
    beam(&mut b, (28, 38, 16), (35, 38, 16), 6, 4, Part::Weapon);
    // Мачта. Ведётся от крыши корпуса, а не от высоты башни: первая
    // редакция начинала её на 42 и оставляла восемь вокселей пустоты
    // под ней — сенсор висел в воздухе и был отрезан от ядра.
    fill(&mut b, (6, 10), (34, 42), (14, 18), Part::Armour);
    fill(&mut b, (5, 11), (42, 48), (13, 19), Part::Sensor);
    fill(&mut b, (16, 20), (24, 28), (14, 18), Part::Core);
    seat(b, "осадный шагоход")
}

/// **Командная машина.** 8.0 × 11.0 × 7.0 м, том 32×44×28.
///
/// Не самая крупная и не самая сильная — самая дорогая. Силуэт
/// человекоподобный нарочно: командира надо узнавать в толпе.
pub fn commander() -> UnitBody {
    let mut b = UnitBody::new_scaled(32, 44, 28, 4, MM);
    fill(&mut b, (6, 16), (0, 3), (8, 20), Part::Armour);
    fill(&mut b, (16, 26), (0, 3), (8, 20), Part::Armour);
    beam(&mut b, (11, 3, 14), (11, 19, 14), 7, 6, Part::Armour);
    beam(&mut b, (21, 3, 14), (21, 19, 14), 7, 6, Part::Armour);
    // Торс, плечи и ранец.
    fill(&mut b, (6, 26), (18, 34), (7, 21), Part::Armour);
    fill(&mut b, (4, 28), (28, 33), (9, 19), Part::Armour);
    fill(&mut b, (3, 9), (20, 32), (6, 22), Part::Engine);
    // Голова с сенсором.
    fill(&mut b, (13, 19), (34, 40), (11, 17), Part::Armour);
    fill(&mut b, (13, 19), (36, 40), (9, 11), Part::Sensor);
    // Правая рука — орудие, левая — строительная.
    fill(&mut b, (24, 30), (24, 32), (8, 14), Part::Weapon);
    beam(&mut b, (29, 28, 11), (31, 28, 11), 5, 4, Part::Weapon);
    fill(&mut b, (24, 30), (22, 26), (16, 20), Part::Armour);
    fill(&mut b, (14, 18), (22, 26), (12, 16), Part::Core);
    seat(b, "командная машина")
}

