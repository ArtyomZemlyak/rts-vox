//! Набор тел: от лёгкого танка до экспериментальной машины.
//!
//! **Зачем.** Пока в проекте было одно тело — танк шесть метров, — весь
//! масштаб держался на одном числе, и проверить его было не с чем.
//! Крупная машина ломает сразу три вещи: ширину колонки тома, плотность
//! деталей и пересчёт вокселей в мировые единицы. Набор нужен, чтобы
//! каждая из трёх ломалась в тесте, а не в игре.
//!
//! **Размеры выбраны нами**, а не списаны из чужой игры: воспроизводится
//! разброс — обычная машина в единицы метров, экспериментальная
//! в десятки, — а не чей-то конкретный чертёж. Разброс и есть то, что
//! нагружает движок.
//!
//! **Воксель у всех один: канонические 0.25 м** (ADR-094). Первая
//! редакция давала гигантам воксель в метр, чтобы они влезли
//! в 64-битную колонку, и они выходили вчетверо грубее танка —
//! не «большими», а «из кубиков покрупнее». Колонка стала многословной
//! (ADR-179), и подгонка больше не нужна: у всех машин набора
//! четыре воксела на метр.

use crate::unit::{Part, UnitBody};

/// Ребро воксела тела в миллиметрах — канон (ADR-094).
const MM: u16 = 250;

/// Вокселей в метре — только для проверки плотности.
#[cfg(test)]
const V: usize = 4;

/// Заполнить параллелепипед. Диапазоны полуоткрытые, выход за габарит
/// обрезается: формы строятся от руки, и промах на воксель не должен
/// ронять сборку.
fn fill(b: &mut UnitBody, xs: (usize, usize), ys: (usize, usize), zs: (usize, usize), p: Part) {
    let (nx, ny, nz) = (b.vol.nx as usize, b.vol.ny as usize, b.vol.nz as usize);
    for z in zs.0..zs.1.min(nz) {
        for y in ys.0..ys.1.min(ny) {
            for x in xs.0..xs.1.min(nx) {
                b.set(x, y, z, p);
            }
        }
    }
}

/// Слой-диск: круг радиуса `r` вокруг `(cx, cz)`, высотой `ys`.
///
/// Сравниваются **квадраты** — корень в симуляции последнее средство
/// (`CLAUDE.md`, ADR-071), а здесь он и не нужен.
fn disc(b: &mut UnitBody, c: (usize, usize), r: i32, ys: (usize, usize), p: Part) {
    ring(b, c, r, 0, ys, p);
}

/// Кольцо: диск радиуса `r` без середины радиуса `hole`.
///
/// Нужно на пояса брони и дульные насадки — сплошной диск там
/// читается как пробка.
fn ring(b: &mut UnitBody, c: (usize, usize), r: i32, hole: i32, ys: (usize, usize), p: Part) {
    let (nx, ny, nz) = (b.vol.nx as i32, b.vol.ny as usize, b.vol.nz as i32);
    let (r2, h2) = (r * r, hole * hole);
    for y in ys.0..ys.1.min(ny) {
        let yy = y;
        for dz in -r..=r {
            for dx in -r..=r {
                let d2 = dx * dx + dz * dz;
                if d2 > r2 || d2 < h2 {
                    continue;
                }
                let (x, z) = (c.0 as i32 + dx, c.1 as i32 + dz);
                if x < 0 || z < 0 || x >= nx || z >= nz {
                    continue;
                }
                b.set(x as usize, yy, z as usize, p);
            }
        }
    }
}

/// Отрезок из блоков между двумя точками — конечность или ствол.
///
/// Толщина тает к дальнему концу: нога, у которой голень той же
/// толщины, что бедро, читается как труба.
fn beam(
    b: &mut UnitBody,
    a: (i32, i32, i32),
    e: (i32, i32, i32),
    t0: i32,
    t1: i32,
    p: Part,
) {
    let d = (e.0 - a.0, e.1 - a.1, e.2 - a.2);
    let steps = d.0.abs().max(d.1.abs()).max(d.2.abs()).max(1);
    for i in 0..=steps {
        let (x, y, z) = (
            a.0 + d.0 * i / steps,
            a.1 + d.1 * i / steps,
            a.2 + d.2 * i / steps,
        );
        let t = t0 + (t1 - t0) * i / steps;
        let h = t / 2;
        fill(
            b,
            ((x - h).max(0) as usize, (x + t - h).max(0) as usize),
            ((y - h).max(0) as usize, (y + t - h).max(0) as usize),
            ((z - h).max(0) as usize, (z + t - h).max(0) as usize),
            p,
        );
    }
}

/// Посадить ядро и убедиться, что оно село.
///
/// Тело без ядра неубиваемо, и молча выпустить такое — ошибка, которую
/// увидит только бой. Поэтому паника здесь, на сборке шаблона: это
/// не пользовательский ввод, а наша собственная разметка.
fn seat(mut b: UnitBody, name: &str) -> UnitBody {
    assert!(b.seat_core(), "{name}: ядро не село");
    b
}

