//! Замер: во что обходится ребро воксела тела в сто миллиметров.
//!
//! Не утверждение, а печать чисел: тест проверяет только то, что
//! **габарит не меняется** — пересэмплирование дробит кубики, а не
//! растягивает машину.

use voxel::unit::WORLD_MM;

/// **Пересэмплирование сохраняет размер машины.**
///
/// Шесть метров остаются шестью метрами, меняется только дробность.
/// Промах здесь не падает и не ругается: танк просто становится
/// другого размера, и заметно это уже на снимке.
#[test]
fn resampling_keeps_the_machine_the_same_size() {
    for (name, b) in voxel::roster::all() {
        let (x, y, z) = b.extent_mm();
        let Ok(r) = b.resampled(100) else { continue };
        let (rx, ry, rz) = r.extent_mm();
        // Допуск — один воксел нового масштаба на сторону: сетка целая,
        // и уложить 250 в 100 без остатка нельзя.
        for (a, c, axis) in [(x, rx, "X"), (y, ry, "Y"), (z, rz, "Z")] {
            let d = a.abs_diff(c);
            assert!(
                d <= 100,
                "{name}: по {axis} было {a} мм, стало {c} мм — разница {d}"
            );
        }
        println!(
            "{name}: {}×{}×{} по {} мм ({} вокселей) -> {}×{}×{} по {} мм ({} вокселей)",
            b.vol.nx,
            b.vol.ny,
            b.vol.nz,
            b.mm,
            b.solid_count(),
            r.vol.nx,
            r.vol.ny,
            r.vol.nz,
            r.mm,
            r.solid_count()
        );
    }
    println!("мировой воксел {WORLD_MM} мм");
}

/// **Отказ пересэмплировать называет причину.**
///
/// Тело в сто миллиметров влезает не всякое: колонка держит
/// не больше 255 вокселей по высоте. Молчаливый отказ дал бы машину
/// в прежнем масштабе посреди новых — и это было бы видно только
/// на снимке.
#[test]
fn a_refusal_says_why() {
    let mut refused = 0;
    for (name, b) in voxel::roster::all() {
        if let Err(e) = b.resampled(100) {
            let why = e.why();
            assert!(!why.is_empty(), "{name}: отказ без причины");
            println!("{name}: {why}");
            refused += 1;
        }
    }
    println!("отказов {refused}");
}
