#[cfg(test)]
mod tests {
    use super::*;

    /// **Перевод в линейное пространство не выдуман.** Контрольные точки
    /// стандарта: ноль в ноль, единица в единицу, середина шкалы —
    /// примерно в пятую часть.
    #[test]
    fn srgb_to_linear_hits_the_known_points() {
        assert_eq!(to_linear([0.0, 0.0, 0.0])[0], 0.0);
        assert!((to_linear([1.0, 1.0, 1.0])[0] - 1.0).abs() < 1e-6);
        assert!((to_linear([0.5, 0.5, 0.5])[0] - 0.2140).abs() < 1e-3);
    }

    /// **У каждого материала пака свой цвет.** Одинаковый цвет у двух
    /// материалов — это не картинка, а потерянная разница.
    #[test]
    fn every_material_has_its_own_colour() {
        for (i, a) in PALETTE.iter().enumerate() {
            for b in PALETTE.iter().skip(i + 1) {
                assert_ne!(a.id, b.id, "номер {} в палитре дважды", a.id);
                assert_ne!(a.srgb, b.srgb, "материалы {} и {} одного цвета", a.id, b.id);
            }
        }
    }

    /// **Палитра покрывает ванильный пак.** Список номеров здесь и
    /// в `data/materials.ron` обязан совпадать: иначе мир красится
    /// «неизвестной» фуксией, и заметит это не тест, а скриншот.
    #[test]
    fn the_palette_covers_the_vanilla_pack() {
        let ron = include_str!("../../../data/materials.ron");
        // Воздух не рисуется никогда, поэтому его в палитре нет.
        let mut want: Vec<Mat> = Vec::new();
        for line in ron.lines() {
            let Some(rest) = line.split_once("id:") else { continue };
            let num: String = rest.1.trim_start().chars().take_while(|c| c.is_ascii_digit()).collect();
            if let Ok(id) = num.parse::<Mat>() {
                if id != voxel::store::AIR {
                    want.push(id);
                }
            }
        }
        assert!(want.len() >= 10, "материалы из пака не разобрались: {want:?}");
        for id in want {
            assert!(look(id).is_some(), "материал {id} из пака не покрашен");
        }
    }

    /// **Руда отличается от породы не только цветом.** Разная
    /// шероховатость — единственное, ради чего заведён класс.
    #[test]
    fn ore_and_rock_are_not_the_same_surface() {
        assert_ne!(surface(Class::Rock), surface(Class::Ore));
        assert_eq!(class(2), Class::Rock);
        assert_eq!(class(17), Class::Ore);
    }

    /// **Стороны различимы.** Цвет — единственное, что отличает своих
    /// от чужих на расстоянии.
    #[test]
    fn the_two_sides_are_not_the_same_colour() {
        assert_ne!(SIDE_TINT[0], SIDE_TINT[1]);
    }

    /// **Солнце нормировано и светит вниз.** `looking_to`
    /// с ненормированным направлением кладёт масштаб в матрицу поворота
    /// света, а солнце из-под земли не освещает ничего — и то и другое
    /// видно только на картинке, то есть слишком поздно.
    #[test]
    fn the_sun_points_down_and_is_normalised() {
        for e in [0.05f32, 0.33, 0.8, 1.4] {
            for a in [-2.0f32, -0.75, 0.0, 2.5] {
                let d = sun_dir_at(e, a);
                let n = (d[0] * d[0] + d[1] * d[1] + d[2] * d[2]).sqrt();
                assert!((n - 1.0).abs() < 1e-5, "не нормирован: {n}");
                assert!(d[1] < 0.0, "солнце светит вверх при высоте {e}");
                // Высота восстанавливается из вектора: перепутанный
                // синус с косинусом проходит проверку на длину.
                assert!(((-d[1]).asin() - e).abs() < 1e-5);
            }
        }
    }

    /// **Плитка фаски темнее у ребра и светлее в середине.** Знак здесь
    /// перепутать легко, а видно это только вблизи: перевёрнутая плитка
    /// даёт светлую решётку по швам вместо тени.
    #[test]
    fn the_chamfer_is_dark_at_the_edge() {
        let mid = chamfer_at(0.5, 0.5);
        let edge = chamfer_at(0.0, 0.5);
        let corner = chamfer_at(0.0, 0.0);
        assert!(edge < mid, "ребро {edge} не темнее середины {mid}");
        assert!(corner <= edge + 1e-6, "угол светлее ребра");
        assert!((mid - 1.0).abs() < 1e-6, "середина не единица: {mid}");
        // Плитка обязана быть симметричной: иначе соседние воксели
        // сойдутся швом разной яркости.
        for (u, v) in [(0.2f32, 0.7f32), (0.05, 0.5), (0.31, 0.13)] {
            assert!((chamfer_at(u, v) - chamfer_at(1.0 - u, v)).abs() < 1e-6);
            assert!((chamfer_at(u, v) - chamfer_at(v, u)).abs() < 1e-6);
        }
    }

    /// **Уровни детализации выложены целиком и по порядку.** Bevy
    /// читает их из одного буфера по обещанному `mip_level_count`,
    /// и недосчитанный уровень — это чтение за краем.
    #[test]
    fn the_chamfer_tile_carries_a_whole_mip_chain() {
        let t = chamfer_tile();
        assert_eq!(t.size, TILE);
        assert_eq!(t.mips, TILE.trailing_zeros() + 1);
        let mut want = 0usize;
        let mut s = t.size as usize;
        for _ in 0..t.mips {
            want += s * s * 4;
            s /= 2;
        }
        assert_eq!(t.rgba.len(), want, "цепочка уровней не сходится");

        // **Уровни усреднены в линейном пространстве, а не в sRGB.**
        // Единственный пиксель последнего уровня обязан совпасть
        // с линейным средним всей плитки. Усреднение прямо в байтах
        // sRGB даёт заметно светлее — и рельеф вдали становится
        // светлее, чем вблизи, плавно и незаметно.
        let n = TILE as usize;
        let mut sum = 0.0f64;
        for y in 0..n {
            for x in 0..n {
                let u = (x as f32 + 0.5) / TILE as f32;
                let v = (y as f32 + 0.5) / TILE as f32;
                sum += srgb_to_lin(chamfer_at(u, v)) as f64;
            }
        }
        let want_byte = (lin_to_srgb((sum / (n * n) as f64) as f32) * 255.0 + 0.5) as i32;
        let got = t.rgba[t.rgba.len() - 4] as i32;
        assert!((got - want_byte).abs() <= 1, "мельчайший уровень {got}, ждали {want_byte}");
        assert!(got < 255, "плитка не темнеет вовсе");
    }
}
