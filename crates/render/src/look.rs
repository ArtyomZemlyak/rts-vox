// --- Яркость грани по её направлению ---------------------------------
//
// Свет на воксельной сцене приходит сверху — и от солнца, и от неба.
// Верхняя грань получает и то и другое, боковая только половину неба,
// нижняя не получает ничего, кроме отражённого от земли.
//
// Расчёт света это уже учитывает, но **только для прямого солнца**:
// карта окружения у нас низкого разрешения, а щелевое затенение
// работает в экране и до дна ямы не достаёт. Множитель в цвете
// вершины — это та же разница, записанная в альбедо: три умножения
// на выпущенный квад и ноль работы в кадре (ADR-201).
//
// Ради него же читается и яма: у воронки стенки боковые, дно нижнее,
// и потемнение делает её ямой, а не пятном.

/// Множитель яркости грани: верх, бок, низ.
pub const FACE_TOP: f32 = 1.00;
pub const FACE_SIDE: f32 = 0.82;
pub const FACE_BOTTOM: f32 = 0.58;

/// Множитель по оси грани и её знаку. Ось `1` — вертикаль.
#[inline]
pub fn face_tint(axis: usize, positive: bool) -> f32 {
    if axis != 1 {
        FACE_SIDE
    } else if positive {
        FACE_TOP
    } else {
        FACE_BOTTOM
    }
}

/// Линейный цвет вершины материала с учётом направления грани.
#[inline]
pub fn colour_face(m: Mat, axis: usize, positive: bool) -> [f32; 4] {
    let c = colour(m);
    let k = face_tint(axis, positive);
    [c[0] * k, c[1] * k, c[2] * k, c[3]]
}

// --- Фаска на ребре воксела ------------------------------------------
//
// Воксель без фаски выглядит пластилиновым: две соседние грани одного
// цвета сливаются, и куб читается пятном. Настоящая фаска — это
// геометрия, то есть втрое больше вершин у мира, который и так
// пересобирается каждый тик.
//
// Вместо неё — **одна плитка на воксель**, повторяющаяся текстура
// в `base_color`. Она темнеет к ребру и светлеет полоской чуть внутри:
// глаз читает это как скруглённое ребро. Цена — два числа на вершину
// (UV) и ноль работы в кадре; геометрия не меняется вовсе (ADR-199).

/// Сторона плитки в пикселях. Степень двойки: иначе цепочка уровней
/// детализации не делится нацело.
/// Сколько вокселей укладывается в одну плитку по стороне.
///
/// **Не один.** Плитка в воксель повторялась на каждом кубе, и ровная
/// площадь получала правильную сетку — рисунок, которого в природе
/// нет. На четырёх вокселях узор повторяется вчетверо реже, а каждая
/// из шестнадцати клеток внутри плитки получает своё зерно: глазу
/// не за что зацепиться (ADR-211).
pub const TILE_VOXELS: f32 = 4.0;

/// Сторона плитки в пикселях: тридцать два на воксель.
pub const TILE: u32 = 128;

/// Докуда тянется затемнение от ребра, в долях воксела.
const EDGE: f32 = 0.10;
// Насколько темно у самого ребра — у каждого класса своё
// (`Surf::edge`). Числа подобраны снимком, и подобраны вниз: на 0.62
// сетка читалась не фаской, а расчерченной бумагой.
/// Светлая полоска на переломе фаски и её ширина в долях воксела.
const RIM_LIGHT: f32 = 0.045;
const RIM_WIDTH: f32 = 0.04;

/// Плитка со всеми уровнями детализации подряд, RGBA8.
///
/// Уровни обязательны: плитка размером в воксель на дальнем краю карты
/// занимает меньше пикселя, и без них весь рельеф кипел бы муаром.
pub struct Tile {
    pub size: u32,
    pub mips: u32,
    /// Уровни подряд, от нулевого к самому мелкому.
    pub rgba: Vec<u8>,
}

/// Значение из решётки. Та же хеш-функция, что у шума мира: заводить
/// здесь свой генератор незачем, а разные — верный способ развести
/// цвет и нормаль.
fn cell_hash(a: i64, b: i64, salt: i64) -> f32 {
    let mut h = (a.wrapping_mul(374_761_393) ^ b.wrapping_mul(668_265_263) ^ salt.wrapping_mul(2_654_435_761)) as u64;
    h ^= h >> 13;
    h = h.wrapping_mul(1_274_126_177);
    h ^= h >> 16;
    ((h >> 40) as f32 / 8_388_608.0) - 1.0
}

/// Яркость фаски в точке внутри **воксела**, 0..1 в sRGB.
fn chamfer_at(u: f32, v: f32, dark: f32) -> f32 {
    // Расстояние до ближайшего ребра грани.
    let d = u.min(1.0 - u).min(v.min(1.0 - v));
    // Падение к ребру: гладкая ступенька, а не линейная — линейная
    // даёт видимый излом ровно там, где его и не должно быть видно.
    let t = (d / EDGE).clamp(0.0, 1.0);
    let sm = t * t * (3.0 - 2.0 * t);
    let base = dark + (1.0 - dark) * sm;
    // Блик на переломе. Нормали у фаски нет — её изображает эта
    // полоска, и без неё фаска читается просто как грязь по краю.
    let r = ((d - EDGE).abs() / RIM_WIDTH).clamp(0.0, 1.0);
    base + RIM_LIGHT * (1.0 - r) * (1.0 - r)
}


/// Местные координаты: номер воксела внутри плитки и точка внутри него.
fn split(u: f32, v: f32) -> (i64, i64, f32, f32) {
    let (su, sv) = (u * TILE_VOXELS, v * TILE_VOXELS);
    (su.floor() as i64, sv.floor() as i64, su.fract(), sv.fract())
}

/// Яркость цветовой плитки класса в точке `(u, v)` **плитки**.
fn albedo_at(c: Class, u: f32, v: f32) -> f32 {
    let s = surf(c);
    let (vx, vz, fu, fv) = split(u, v);
    // Зерно: решётка внутри воксела, посоленная номером воксела —
    // поэтому соседние кубы не повторяют друг друга.
    let salt = vx.wrapping_mul(73).wrapping_add(vz.wrapping_mul(9173));
    let (gu, gv) = ((fu * s.cells).floor() as i64, (fv * s.cells).floor() as i64);
    let g = cell_hash(gu, gv, salt);
    // Каждый воксель к тому же чуть светлее или темнее соседа.
    let per_voxel = 0.06 * cell_hash(vx, vz, 0x5EED);
    let mut a = chamfer_at(fu, fv, s.edge) * (1.0 + s.grain * g + per_voxel);
    // Вкрапления: редкие яркие крупинки поверх зерна.
    if s.speck > 0.0 {
        let f = cell_hash(gu, gv, salt ^ 0x51E);
        if f > 1.0 - 2.0 * s.speck {
            a *= 1.45;
        }
    }
    a.clamp(0.0, 1.0)
}

/// Касательная нормаль в точке плитки. Единичная, `z` наружу.
fn normal_at(c: Class, u: f32, v: f32) -> [f32; 3] {
    let s = surf(c);
    let (vx, vz, fu, fv) = split(u, v);
    // Выгиб: наклон растёт к краю воксела и на самом краю обнуляется,
    // иначе на стыке двух вокселей нормаль прыгает и шов виден полосой.
    let bend = |t: f32| -> f32 {
        let x = t * 2.0 - 1.0;
        x * (1.0 - x * x)
    };
    let mut nx = -s.dome * bend(fu);
    let mut ny = -s.dome * bend(fv);
    let salt = vx.wrapping_mul(73).wrapping_add(vz.wrapping_mul(9173));
    let (gu, gv) = ((fu * s.cells).floor() as i64, (fv * s.cells).floor() as i64);
    nx += s.bump * cell_hash(gu, gv, salt ^ 0x0B1);
    ny += s.bump * cell_hash(gu, gv, salt ^ 0x0B2);
    let len = (nx * nx + ny * ny + 1.0).sqrt();
    [nx / len, ny / len, 1.0 / len]
}

/// Цветовая плитка класса со всеми уровнями. **sRGB**: это цвет.
pub fn surface_tile(c: Class) -> Tile {
    let n = TILE as usize;
    let mut cur = vec![0.0f32; n * n];
    for y in 0..n {
        for x in 0..n {
            // Центр пикселя, а не угол: с углом плитка получается
            // на полпикселя сдвинутой и швы на стыке не сходятся.
            let u = (x as f32 + 0.5) / TILE as f32;
            let v = (y as f32 + 0.5) / TILE as f32;
            cur[y * n + x] = srgb_to_lin(albedo_at(c, u, v));
        }
    }
    let mut rgba = Vec::new();
    let mut mips = 0u32;
    let mut cs = n;
    loop {
        push_level(&cur, cs, &mut rgba);
        mips += 1;
        if cs == 1 {
            break;
        }
        // Усреднение **в линейном пространстве**: усреднить sRGB
        // напрямую значит осветлить каждый следующий уровень,
        // и рельеф вдали станет светлее, чем вблизи.
        let ns = cs / 2;
        let mut next = vec![0.0f32; ns * ns];
        for y in 0..ns {
            for x in 0..ns {
                let i = |yy: usize, xx: usize| cur[yy * cs + xx];
                next[y * ns + x] = 0.25
                    * (i(2 * y, 2 * x) + i(2 * y, 2 * x + 1) + i(2 * y + 1, 2 * x) + i(2 * y + 1, 2 * x + 1));
            }
        }
        cur = next;
        cs = ns;
    }
    Tile { size: TILE, mips, rgba }
}

/// Плитка нормалей класса. **Линейная**, не sRGB: это вектор,
/// а не цвет, и гамма его искривит.
pub fn normal_tile(c: Class) -> Tile {
    let n = TILE as usize;
    let mut cur: Vec<[f32; 3]> = vec![[0.0; 3]; n * n];
    for y in 0..n {
        for x in 0..n {
            let u = (x as f32 + 0.5) / TILE as f32;
            let v = (y as f32 + 0.5) / TILE as f32;
            cur[y * n + x] = normal_at(c, u, v);
        }
    }
    let mut rgba = Vec::new();
    let mut mips = 0u32;
    let mut cs = n;
    loop {
        push_normal_level(&cur, cs, &mut rgba);
        mips += 1;
        if cs == 1 {
            break;
        }
        let ns = cs / 2;
        let mut next = vec![[0.0f32; 3]; ns * ns];
        for y in 0..ns {
            for x in 0..ns {
                let i = |yy: usize, xx: usize| cur[yy * cs + xx];
                let mut a = [0.0f32; 3];
                for q in [i(2 * y, 2 * x), i(2 * y, 2 * x + 1), i(2 * y + 1, 2 * x), i(2 * y + 1, 2 * x + 1)] {
                    for k in 0..3 {
                        a[k] += q[k] * 0.25;
                    }
                }
                // Усреднённые векторы **перенормируются**: сумма
                // единичных единичной не бывает, и без этого дальние
                // уровни светили бы иначе, чем ближние.
                let l = (a[0] * a[0] + a[1] * a[1] + a[2] * a[2]).sqrt().max(1e-6);
                next[y * ns + x] = [a[0] / l, a[1] / l, a[2] / l];
            }
        }
        cur = next;
        cs = ns;
    }
    Tile { size: TILE, mips, rgba }
}

/// Уровень из нормалей — в байты, со сдвигом из −1..1 в 0..1.
fn push_normal_level(v: &[[f32; 3]], n: usize, out: &mut Vec<u8>) {
    out.reserve(n * n * 4);
    for q in v.iter().take(n * n) {
        let b = |x: f32| ((x * 0.5 + 0.5) * 255.0 + 0.5).clamp(0.0, 255.0) as u8;
        out.extend_from_slice(&[b(q[0]), b(q[1]), b(q[2]), 255]);
    }
}

/// Уровень из линейных яркостей — в байты sRGB.
fn push_level(lin: &[f32], n: usize, out: &mut Vec<u8>) {
    out.reserve(n * n * 4);
    for v in lin.iter().take(n * n) {
        let b = (lin_to_srgb(*v) * 255.0 + 0.5).clamp(0.0, 255.0) as u8;
        out.extend_from_slice(&[b, b, b, 255]);
    }
}

fn srgb_to_lin(u: f32) -> f32 {
    if u <= 0.04045 {
        u / 12.92
    } else {
        ((u + 0.055) / 1.055).powf(2.4)
    }
}

fn lin_to_srgb(u: f32) -> f32 {
    if u <= 0.003_130_8 {
        u * 12.92
    } else {
        1.055 * u.powf(1.0 / 2.4) - 0.055
    }
}

// --- Свет, небо, атмосфера -------------------------------------------
//
// Небо у нас **процедурное**: `bevy_pbr::atmosphere` считает рассеяние
// и из одного положения солнца выдаёт разом цвет неба, цвет света
// у земли, дымку по глубине и карту окружения для отражений. Плоская
// заливка и три подобранных на глаз источника заменены одним числом —
// высотой солнца (ADR-198).

/// Высота солнца над горизонтом, радианы. **Главное число картинки.**
/// В зените тени не видно, и рельеф читается как заливка; у горизонта
/// тень длинная, свет тёплый, а теневой стороне достаётся голубизна
/// неба.
pub const SUN_ELEVATION: f32 = 0.33;

/// Азимут солнца, радианы: поворот источника вокруг вертикали.
pub const SUN_AZIMUTH: f32 = -0.75;

/// Куда светит солнце, в мировых осях.
///
/// Функция, а не константа: `sin`/`cos` в `const fn` нет, а держать
/// вектор и углы порознь значит рассинхронизировать их при первой же
/// правке.
pub fn sun_dir() -> [f32; 3] {
    sun_dir_at(SUN_ELEVATION, SUN_AZIMUTH)
}

/// То же для произвольного времени суток: высота и азимут в радианах.
///
/// Вектор нормирован по построению, и это важнее, чем кажется:
/// `looking_to` с ненормированным направлением даёт масштаб в матрице
/// поворота света.
pub fn sun_dir_at(elevation: f32, azimuth: f32) -> [f32; 3] {
    let (se, ce) = (elevation.sin(), elevation.cos());
    let (sa, ca) = (azimuth.sin(), azimuth.cos());
    [-ce * sa, -se, -ce * ca]
}

/// Солнце белое, а не тёплое.
///
/// Тёплым его делает атмосфера: у горизонта синева рассеивается
/// сильнее красного. Подкрасить источник руками значит покрасить
/// дважды, и на закате получить оранжевое вдвое.
pub const SUN_SRGB: [f32; 3] = [1.0, 1.0, 1.0];

/// Люксы **до** атмосферы. Именно это число ждёт рассеяние на входе:
/// 10 000 у Bevy — уже отфильтрованный воздухом дневной свет, и подать
/// его сюда значит отфильтровать второй раз.
pub const SUN_LUX: f32 = 130_000.0;

/// Экспозиция камеры, EV100. Держится в паре с `SUN_LUX`: яркость
/// источника и экспозиция — одна настройка, разнесённая по двум
/// компонентам, и менять их порознь нельзя.
pub const EV100: f32 = 13.1;

/// Диск солнца в небе: угловой размер в радианах и яркость.
///
/// Земной диск (0.0093 рад) на кадре RTS — несколько пикселей. Берём
/// крупнее: солнце здесь опора композиции, а не астрономия.
pub const SUN_DISK_SIZE: f32 = 0.028;
pub const SUN_DISK_INTENSITY: f32 = 1.0;

/// Яркость карты окружения, снятой с неба. Она же весь заполняющий
/// свет: отдельный «свет неба» и ровный ambient не нужны, когда небо
/// есть на самом деле.
///
/// Больше единицы намеренно. Физически верное значение — ровно
/// единица, и при низком солнце оно даёт теневой стороне строя
/// почти чёрный: по картинке красиво, по игре — половину войска
/// не видно. Полторы-две поднимают тень, не трогая ни контраст,
/// ни цвет.
pub const SKY_IBL: f32 = 1.7;
/// Сторона кубкарты окружения. Отражения у нас размытые, деталей в них
/// не читается, а пересчёт идёт каждый кадр.
pub const SKY_IBL_SIZE: u32 = 128;

/// Ровный фон — страховка, а не свет. Атмосфера требует вычислительных
/// шейдеров, и на машине без них её плагин молча не загрузится; без
