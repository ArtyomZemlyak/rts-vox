//! Числа картинки: свет, небо, палитра материалов.
//!
//! **Это не игровые числа.** Цвет породы и яркость солнца не меняют ни
//! одного исхода и в хеш состояния не входят, поэтому им не место
//! в `data/*.ron` рядом со стоимостью и уроном. Но и рассыпать их по
//! коду нельзя: подобранная картинка — это дюжина чисел, которые
//! обязаны меняться вместе, иначе подбор превращается в поиск по файлам.
//!
//! Направлений здесь **несколько**, и переключаются они целиком
//! (ADR-214): свет, палитра, тонмаппинг, цветокоррекция, дымка,
//! шероховатость и толщина теней — один набор. Половина набора от одного
//! направления и половина от другого не даёт третьего, она даёт грязь.
//!
//! Плавающая точка здесь разрешена — рендер в хеш не входит
//! (`docs/03-determinism.md`).
//!
//! Bevy здесь нет намеренно: модуль обязан проверяться headless
//! и собираться без окна (`CLAUDE.md`, «тесты до рендера»). Поэтому
//! тонмаппинг и цветокоррекция описаны своими типами, а переводят их
//! в компоненты Bevy окна.

use std::sync::atomic::{AtomicU8, Ordering};

use voxel::store::Mat;

// --- Направление ------------------------------------------------------
//
// Направление — это **весь** набор чисел картинки разом. Оно живёт
// в одной глобальной ячейке на процесс, и ставит её окно один раз при
// разборе ключей. Глобальное состояние запрещено в симуляции и всём,
// от чего она зависит (`CLAUDE.md`); рендер в этот список не входит
// и в хеш не попадает.

/// Художественное направление картинки.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[repr(u8)]
pub enum Look {
    /// Как было до ADR-214: дневное солнце, честные материалы.
    /// Точка отсчёта, с которой сравнивают остальные три.
    Base = 0,
    /// Диорама: контровой свет, тёплый ключ и холодная тень,
    /// повышенная насыщенность, виньетка и малая глубина резкости —
    /// макет под лампой.
    Diorama = 1,
    /// Графика: сжатая палитра, ступенчатое затенение, плоские тени,
    /// подчёркнутое ребро воксела. Бликов нет вовсе.
    Graphic = 2,
    /// Техно: холодная приглушённая гамма, высокий контраст, металл
    /// читается металлом, глубокая дымка — полигон испытаний.
    Techno = 3,
    /// Вангеры: охра и лиловый камень, склон другого цвета, чем верх,
    /// низкое боковое солнце и насыщенная палитра — рельеф читается
    /// цветом, как в игре 1998 года, откуда и имя (ADR-235).
    Vangers = 4,
}

/// Сколько направлений. По ним индексируются таблицы палитры.
pub const LOOKS: usize = 5;

/// Все направления по порядку номеров. Номер — это индекс в таблицах,
/// и перечень обязан идти тем же порядком.
pub const LOOK_ALL: [Look; LOOKS] = [
    Look::Base,
    Look::Diorama,
    Look::Graphic,
    Look::Techno,
    Look::Vangers,
];

/// Имя направления для ключа командной строки и для отчёта.
pub fn look_name(l: Look) -> &'static str {
    match l {
        Look::Base => "базовый",
        Look::Diorama => "диорама",
        Look::Graphic => "графика",
        Look::Techno => "техно",
        Look::Vangers => "вангеры",
    }
}

/// Направление по имени. Принимает и русское имя, и латинское: ключ
/// набирают в терминале, а раскладка не всегда та.
pub fn parse_look(s: &str) -> Option<Look> {
    match s.trim().to_lowercase().as_str() {
        "базовый" | "база" | "base" => Some(Look::Base),
        "диорама" | "diorama" => Some(Look::Diorama),
        "графика" | "graphic" => Some(Look::Graphic),
        "техно" | "techno" => Some(Look::Techno),
        "вангеры" | "vangers" => Some(Look::Vangers),
        _ => None,
    }
}

/// Выбранное направление. Номер, а не структура: атомарная ячейка
/// читается из любого места без замка, а набор чисел достаётся по номеру.
///
/// Умолчание — **диорама** (ADR-235): это направление владелец выбрал
/// по снимкам, и всё, что делалось ради красоты, делалось на нём.
/// Базовое осталось точкой отсчёта для замеров и включается ключом.
static ACTIVE: AtomicU8 = AtomicU8::new(Look::Diorama as u8);

/// Выбрать направление. Зовётся **один раз**, при разборе ключей окна:
/// плитки поверхностей строятся на старте, и смена направления после
/// этого перекрасила бы вершины, не тронув плитки.
pub fn set(l: Look) {
    ACTIVE.store(l as u8, Ordering::Relaxed);
}

/// Выбранное направление.
pub fn active() -> Look {
    LOOK_ALL[(ACTIVE.load(Ordering::Relaxed) as usize).min(LOOKS - 1)]
}

/// sRGB → линейный.
///
/// Нужна не для красоты: цвет вершины в Bevy 0.19.1 **подменяет**
/// `base_color` материала (`pbr_fragment.wgsl`), а `base_color`
/// линейный. Положить туда sRGB — значит осветлить всё примерно
/// в два раза и не понять почему.
pub fn to_linear(c: [f32; 3]) -> [f32; 4] {
    let f = |u: f32| {
        if u <= 0.04045 {
            u / 12.92
        } else {
            ((u + 0.055) / 1.055).powf(2.4)
        }
    };
    [f(c[0]), f(c[1]), f(c[2]), 1.0]
}

/// Как рисуется материал мира.
///
/// Шероховатость и металличность **не могут** быть свойством вершины:
/// у `StandardMaterial` их читает материал, а не меш. Поэтому вместо
/// числа здесь класс, и на класс приходится по одному материалу Bevy.
/// Классов ровно два: иначе на чанк пришлось бы по вызову отрисовки
/// на каждый материал, а материалов в паке одиннадцать.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[repr(u8)]
pub enum Class {
    /// Грунт: мелкое плотное зерно, матовый, без блика.
    Soil = 0,
    /// Порода: крупные сколы, твёрже и светлее грунта.
    Rock = 1,
    /// Руда: вкрапления, гладкая и металлическая — видно, где копать.
    Ore = 2,
}

/// Сколько классов — столько мешей на чанк и столько материалов.
///
/// Грунт отделён от породы намеренно: пока они делили один класс,
/// у них были одна шероховатость и одна плитка, и земля от камня
/// не отличалась ничем, кроме оттенка (ADR-211).
pub const CLASSES: usize = 3;

/// Цвет и класс материала. Номер явный, как в `data/materials.ron`
