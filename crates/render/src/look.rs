// --- Яркость грани по её направлению ---------------------------------
//
// Свет на воксельной сцене приходит сверху — и от солнца, и от неба.
// Верхняя грань получает и то и другое, боковая только половину неба,
// нижняя не получает ничего, кроме отражённого от земли.
//
// Расчёт света это уже учитывает, но **только для прямого солнца**:
// карта окружения у нас низкого разрешения, а щелевое затенение
// работает в экране и до дна ямы не достаёт. Множитель в цвете
// вершины — это та же разница, записанная в альбедо: три умножения
// на выпущенный квад и ноль работы в кадре (ADR-201).
//
// Ради него же читается и яма: у воронки стенки боковые, дно нижнее,
// и потемнение делает её ямой, а не пятном.

/// Множитель яркости грани: верх, бок, низ.
pub const FACE_TOP: f32 = 1.00;
pub const FACE_SIDE: f32 = 0.82;
pub const FACE_BOTTOM: f32 = 0.58;

/// Множитель по оси грани и её знаку. Ось `1` — вертикаль.
#[inline]
pub fn face_tint(axis: usize, positive: bool) -> f32 {
    if axis != 1 {
        FACE_SIDE
    } else if positive {
        FACE_TOP
    } else {
        FACE_BOTTOM
    }
}

/// Линейный цвет вершины материала с учётом направления грани.
#[inline]
pub fn colour_face(m: Mat, axis: usize, positive: bool) -> [f32; 4] {
    let c = colour(m);
    let k = face_tint(axis, positive);
    [c[0] * k, c[1] * k, c[2] * k, c[3]]
}

// --- Фаска на ребре воксела ------------------------------------------
//
// Воксель без фаски выглядит пластилиновым: две соседние грани одного
// цвета сливаются, и куб читается пятном. Настоящая фаска — это
// геометрия, то есть втрое больше вершин у мира, который и так
// пересобирается каждый тик.
//
// Вместо неё — **одна плитка на воксель**, повторяющаяся текстура
// в `base_color`. Она темнеет к ребру и светлеет полоской чуть внутри:
// глаз читает это как скруглённое ребро. Цена — два числа на вершину
// (UV) и ноль работы в кадре; геометрия не меняется вовсе (ADR-199).

/// Сторона плитки в пикселях. Степень двойки: иначе цепочка уровней
/// детализации не делится нацело.
pub const TILE: u32 = 32;

/// Докуда тянется затемнение от ребра, в долях воксела.
const EDGE: f32 = 0.10;
/// Насколько темно у самого ребра.
///
/// **Число подобрано снимком, и подобрано вниз.** На 0.62 фаска читалась
/// не как фаска, а как расчерченная бумага: воксель тела — четверть
/// метра, и на корпусе танка таких клеток выходит две сотни. Сетка
/// обязана говорить «это сложено из кубов», а не спорить с силуэтом.
const EDGE_DARK: f32 = 0.88;
/// Светлая полоска на переломе фаски и её ширина в долях воксела.
const RIM_LIGHT: f32 = 0.045;
const RIM_WIDTH: f32 = 0.04;

/// Плитка со всеми уровнями детализации подряд, RGBA8 в sRGB.
///
/// Уровни обязательны: плитка размером в воксель на дальнем краю карты
/// занимает меньше пикселя, и без них весь рельеф кипел бы муаром.
pub struct Tile {
    pub size: u32,
    pub mips: u32,
    /// Уровни подряд, от нулевого к самому мелкому.
    pub rgba: Vec<u8>,
}

/// Яркость плитки в точке `(u, v)` внутри воксела, sRGB 0..1.
fn chamfer_at(u: f32, v: f32) -> f32 {
    // Расстояние до ближайшего ребра грани.
    let d = u.min(1.0 - u).min(v.min(1.0 - v));
    // Падение к ребру: гладкая ступенька, а не линейная — линейная
    // даёт видимый излом ровно там, где её и не должно быть видно.
    let t = (d / EDGE).clamp(0.0, 1.0);
    let s = t * t * (3.0 - 2.0 * t);
    let base = EDGE_DARK + (1.0 - EDGE_DARK) * s;
    // Блик на переломе. Нормали у фаски нет — её изображает эта
    // полоска, и без неё фаска читается просто как грязь по краю.
    let r = ((d - EDGE).abs() / RIM_WIDTH).clamp(0.0, 1.0);
    base + RIM_LIGHT * (1.0 - r) * (1.0 - r)
}

/// Собрать плитку фаски вместе с уровнями детализации.
pub fn chamfer_tile() -> Tile {
    let mut mips = 0u32;
    let mut s = TILE;
    while s >= 1 {
        mips += 1;
        if s == 1 {
            break;
        }
        s /= 2;
    }
    let mut rgba: Vec<u8> = Vec::new();

    // Нулевой уровень.
    let n = TILE as usize;
    let mut lin = vec![0.0f32; n * n];
    for y in 0..n {
        for x in 0..n {
            // Центр пикселя, а не угол: с углом плитка получается
            // на полпикселя сдвинутой и швы на стыке не сходятся.
            let u = (x as f32 + 0.5) / TILE as f32;
            let v = (y as f32 + 0.5) / TILE as f32;
            lin[y * n + x] = srgb_to_lin(chamfer_at(u, v));
        }
    }
    push_level(&lin, n, &mut rgba);

    // Остальные — усреднением по четвёркам **в линейном пространстве**.
    // Усреднить sRGB напрямую значит осветлить каждый следующий
    // уровень, и рельеф вдали станет светлее, чем вблизи.
    let mut cur = lin;
    let mut cs = n;
    while cs > 1 {
        let ns = cs / 2;
        let mut next = vec![0.0f32; ns * ns];
        for y in 0..ns {
            for x in 0..ns {
                let i = |yy: usize, xx: usize| cur[yy * cs + xx];
                next[y * ns + x] =
                    0.25 * (i(2 * y, 2 * x) + i(2 * y, 2 * x + 1) + i(2 * y + 1, 2 * x) + i(2 * y + 1, 2 * x + 1));
            }
        }
        push_level(&next, ns, &mut rgba);
        cur = next;
        cs = ns;
    }
    Tile { size: TILE, mips, rgba }
}

/// Уровень из линейных яркостей — в байты sRGB.
fn push_level(lin: &[f32], n: usize, out: &mut Vec<u8>) {
    out.reserve(n * n * 4);
    for v in lin.iter().take(n * n) {
        let b = (lin_to_srgb(*v) * 255.0 + 0.5).clamp(0.0, 255.0) as u8;
        out.extend_from_slice(&[b, b, b, 255]);
    }
}

fn srgb_to_lin(u: f32) -> f32 {
    if u <= 0.04045 {
        u / 12.92
    } else {
        ((u + 0.055) / 1.055).powf(2.4)
    }
}

fn lin_to_srgb(u: f32) -> f32 {
    if u <= 0.003_130_8 {
        u * 12.92
    } else {
        1.055 * u.powf(1.0 / 2.4) - 0.055
    }
}

// --- Свет, небо, атмосфера -------------------------------------------
//
// Небо у нас **процедурное**: `bevy_pbr::atmosphere` считает рассеяние
// и из одного положения солнца выдаёт разом цвет неба, цвет света
// у земли, дымку по глубине и карту окружения для отражений. Плоская
// заливка и три подобранных на глаз источника заменены одним числом —
// высотой солнца (ADR-198).

/// Высота солнца над горизонтом, радианы. **Главное число картинки.**
/// В зените тени не видно, и рельеф читается как заливка; у горизонта
/// тень длинная, свет тёплый, а теневой стороне достаётся голубизна
/// неба.
pub const SUN_ELEVATION: f32 = 0.33;

/// Азимут солнца, радианы: поворот источника вокруг вертикали.
pub const SUN_AZIMUTH: f32 = -0.75;

/// Куда светит солнце, в мировых осях.
///
/// Функция, а не константа: `sin`/`cos` в `const fn` нет, а держать
/// вектор и углы порознь значит рассинхронизировать их при первой же
/// правке.
pub fn sun_dir() -> [f32; 3] {
    sun_dir_at(SUN_ELEVATION, SUN_AZIMUTH)
}

/// То же для произвольного времени суток: высота и азимут в радианах.
///
/// Вектор нормирован по построению, и это важнее, чем кажется:
/// `looking_to` с ненормированным направлением даёт масштаб в матрице
/// поворота света.
pub fn sun_dir_at(elevation: f32, azimuth: f32) -> [f32; 3] {
    let (se, ce) = (elevation.sin(), elevation.cos());
    let (sa, ca) = (azimuth.sin(), azimuth.cos());
    [-ce * sa, -se, -ce * ca]
}

/// Солнце белое, а не тёплое.
///
/// Тёплым его делает атмосфера: у горизонта синева рассеивается
/// сильнее красного. Подкрасить источник руками значит покрасить
/// дважды, и на закате получить оранжевое вдвое.
pub const SUN_SRGB: [f32; 3] = [1.0, 1.0, 1.0];

