// --- Яркость грани по её направлению ---------------------------------
//
// Свет на воксельной сцене приходит сверху — и от солнца, и от неба.
// Верхняя грань получает и то и другое, боковая только половину неба,
// нижняя не получает ничего, кроме отражённого от земли.
//
// Расчёт света это уже учитывает, но **только для прямого солнца**:
// карта окружения у нас низкого разрешения, а щелевое затенение
// работает в экране и до дна ямы не достаёт. Множитель в цвете
// вершины — это та же разница, записанная в альбедо: три умножения
// на выпущенный квад и ноль работы в кадре (ADR-201).
//
// Ради него же читается и яма: у воронки стенки боковые, дно нижнее,
// и потемнение делает её ямой, а не пятном.

/// Множитель яркости грани: верх, бок, низ. У каждого направления свой.
///
/// **У графики это и есть ступенчатое затенение.** Три числа — три
/// ступени яркости, и разводятся они вдвое сильнее базовых: свет
/// в направлении «плоскими пятнами» приходит не от расчёта освещения,
/// а отсюда.
pub fn face_steps(l: Look) -> [f32; 3] {
    match l {
        Look::Base => [1.00, 0.82, 0.58],
        Look::Diorama => [1.00, 0.80, 0.55],
        Look::Graphic => [1.00, 0.68, 0.40],
        Look::Techno => [1.00, 0.78, 0.50],
        // Склон у Вангеров ещё и другого цвета (`Surf::side`), поэтому
        // ступень яркости между ними — вторая, а не единственная.
        Look::Vangers => [1.00, 0.74, 0.46],
    }
}

/// Множитель по оси грани и её знаку. Ось `1` — вертикаль.
#[inline]
pub fn face_tint(axis: usize, positive: bool) -> f32 {
    let s = face_steps(active());
    if axis != 1 {
        s[1]
    } else if positive {
        s[0]
    } else {
        s[2]
    }
}

/// Линейный цвет вершины материала с учётом направления грани.
///
/// Верх и низ красятся цветом материала, бок — **цветом склона**
/// (`colour_side`): у Вангеров склон отличался от равнины оттенком,
/// и здесь это две грани одного воксела, а не две разные породы.
#[inline]
pub fn colour_face(m: Mat, axis: usize, positive: bool) -> [f32; 4] {
    let c = if axis == 1 { colour(m) } else { colour_side(m) };
    let k = face_tint(axis, positive);
    [c[0] * k, c[1] * k, c[2] * k, c[3]]
}

// --- Фаска на ребре воксела ------------------------------------------
//
// Воксель без фаски выглядит пластилиновым: две соседние грани одного
// цвета сливаются, и куб читается пятном. Настоящая фаска — это
// геометрия, то есть втрое больше вершин у мира, который и так
// пересобирается каждый тик.
//
// Вместо неё — **одна плитка на воксель**, повторяющаяся текстура
// в `base_color`. Она темнеет к ребру и светлеет полоской чуть внутри:
// глаз читает это как скруглённое ребро. Цена — два числа на вершину
// (UV) и ноль работы в кадре; геометрия не меняется вовсе (ADR-199).

/// Сторона плитки в пикселях. Степень двойки: иначе цепочка уровней
/// детализации не делится нацело.
/// Сколько вокселей укладывается в одну плитку по стороне.
///
/// **Не один.** Плитка в воксель повторялась на каждом кубе, и ровная
/// площадь получала правильную сетку — рисунок, которого в природе
/// нет. На четырёх вокселях узор повторяется вчетверо реже, а каждая
/// из шестнадцати клеток внутри плитки получает своё зерно: глазу
/// не за что зацепиться (ADR-211).
///
/// Шестнадцать, а не четыре (ADR-235): пятна крупнее воксела кладутся
/// в плитку, потому что цвет вершины один на слитый квад, и класть
/// их в вершину значило бы резать квады. На четырёх вокселях пятну
/// негде поместиться, а на восьми пятна по четыре воксела ложились
/// правильной решёткой, и площадь читалась ковром. Шестнадцать —
/// полтора метра мира: период с игровой камеры не читается.
///
/// UV у рельефа — **мировые** координаты воксела (`geom`), поэтому
/// плитка сидит на сетке мира, а не на сетке квада: квад, порезанный
/// копкой, не меняет рисунка на своих вокселях.
pub const TILE_VOXELS: f32 = 16.0;

/// Сторона плитки в пикселях: тридцать два на воксель. Степень двойки:
/// иначе цепочка уровней детализации не делится нацело.
pub const TILE: u32 = 512;

/// Докуда тянется затемнение от ребра, в долях воксела.
const EDGE: f32 = 0.10;
// Насколько темно у самого ребра — у каждого класса своё
// (`Surf::edge`). Числа подобраны снимком, и подобраны вниз: на 0.62
// сетка читалась не фаской, а расчерченной бумагой.
/// Светлая полоска на переломе фаски и её ширина в долях воксела.
const RIM_LIGHT: f32 = 0.045;
const RIM_WIDTH: f32 = 0.04;

/// Плитка со всеми уровнями детализации подряд, RGBA8.
///
/// Уровни обязательны: плитка размером в воксель на дальнем краю карты
/// занимает меньше пикселя, и без них весь рельеф кипел бы муаром.
pub struct Tile {
    pub size: u32,
    pub mips: u32,
    /// Уровни подряд, от нулевого к самому мелкому.
    pub rgba: Vec<u8>,
}

/// Значение из решётки. Та же хеш-функция, что у шума мира: заводить
/// здесь свой генератор незачем, а разные — верный способ развести
/// цвет и нормаль.
fn cell_hash(a: i64, b: i64, salt: i64) -> f32 {
    let mut h = (a.wrapping_mul(374_761_393)
        ^ b.wrapping_mul(668_265_263)
        ^ salt.wrapping_mul(2_654_435_761)) as u64;
    h ^= h >> 13;
    h = h.wrapping_mul(1_274_126_177);
    h ^= h >> 16;
    ((h >> 40) as f32 / 8_388_608.0) - 1.0
}

/// Яркость фаски в точке внутри **воксела**, 0..1 в sRGB.
fn chamfer_at(u: f32, v: f32, dark: f32) -> f32 {
    // Расстояние до ближайшего ребра грани.
    let d = u.min(1.0 - u).min(v.min(1.0 - v));
    // Падение к ребру: гладкая ступенька, а не линейная — линейная
    // даёт видимый излом ровно там, где его и не должно быть видно.
    let t = (d / EDGE).clamp(0.0, 1.0);
    let sm = t * t * (3.0 - 2.0 * t);
    let base = dark + (1.0 - dark) * sm;
    // Блик на переломе. Нормали у фаски нет — её изображает эта
    // полоска, и без неё фаска читается просто как грязь по краю.
    let r = ((d - EDGE).abs() / RIM_WIDTH).clamp(0.0, 1.0);
    base + RIM_LIGHT * (1.0 - r) * (1.0 - r)
}

/// Местные координаты: номер воксела внутри плитки и точка внутри него.
fn split(u: f32, v: f32) -> (i64, i64, f32, f32) {
    let (su, sv) = (u * TILE_VOXELS, v * TILE_VOXELS);
    (su.floor() as i64, sv.floor() as i64, su.fract(), sv.fract())
}

/// Плавный шум крупнее воксела: решётка из `n` узлов на сторону
/// плитки **с заворотом**, чтобы плитка сходилась сама с собой.
/// Значение в −1..1.
fn patch_at(u: f32, v: f32, n: i64, salt: i64) -> f32 {
    let (su, sv) = (u * n as f32, v * n as f32);
    let (i, j) = (su.floor() as i64, sv.floor() as i64);
    let sm = |t: f32| t * t * (3.0 - 2.0 * t);
    let (fu, fv) = (sm(su - i as f32), sm(sv - j as f32));
    let h = |a: i64, b: i64| cell_hash(a.rem_euclid(n), b.rem_euclid(n), salt);
    let top = h(i, j) + (h(i + 1, j) - h(i, j)) * fu;
    let bot = h(i, j + 1) + (h(i + 1, j + 1) - h(i, j + 1)) * fu;
    top + (bot - top) * fv
}

/// Зерно, пятна и вкрапление в точке плитки — то, что делят цветовая
/// плитка и плитка свойств. Держать их порознь значило бы развести:
/// скол блестел бы не там, где он нарисован.
struct Grain {
    /// Зерно, −1..1.
    g: f32,
    /// Пятно крупнее воксела, −1..1: два октава, по четыре и по два
    /// воксела. **Одно на воксель**: шум берётся в центре воксела,
    /// и пятно — это кучка вокселей одного тона, а не плавный бугор.
    /// Плавный бугор на решётке узлов сидел правильной сеткой,
    /// и площадь читалась ковром; кучка вокселей читается землёй.
    p: f32,
    /// Воксель целиком светлее или темнее соседа, −1..1.
    voxel: f32,
    /// Попала ли точка во вкрапление.
    speck: bool,
}

fn grain_at(s: &Surf, vx: i64, vz: i64, fu: f32, fv: f32) -> Grain {
    // Зерно: решётка внутри воксела, посоленная номером воксела —
    // поэтому соседние кубы не повторяют друг друга.
    let salt = vx.wrapping_mul(73).wrapping_add(vz.wrapping_mul(9173));
    let (gu, gv) = ((fu * s.cells).floor() as i64, (fv * s.cells).floor() as i64);
    let g = cell_hash(gu, gv, salt);
    // Пятно в центре воксела: узлов на плитку — по одному на четыре
    // и на два воксела.
    let (cu, cv) = (
        (vx as f32 + 0.5) / TILE_VOXELS,
        (vz as f32 + 0.5) / TILE_VOXELS,
    );
    let n = TILE_VOXELS as i64;
    let p = 0.6 * patch_at(cu, cv, n / 4, 0x9A7) + 0.4 * patch_at(cu, cv, n / 2, 0x9A8);
    let voxel = cell_hash(vx, vz, 0x5EED);
    let speck = s.speck > 0.0 && cell_hash(gu, gv, salt ^ 0x51E) > 1.0 - 2.0 * s.speck;
    Grain { g, p, voxel, speck }
}

/// Цвет плитки класса в точке `(u, v)` **плитки**, sRGB.
///
/// Плитка умножается на цвет вершины, поэтому в среднем она серая:
/// оттенок здесь — отклонение от цвета материала, а не сам цвет.
fn albedo_at(l: Look, c: Class, u: f32, v: f32) -> [f32; 3] {
    let s = surf_of(l, c);
    let (vx, vz, fu, fv) = split(u, v);
    let n = grain_at(&s, vx, vz, fu, fv);
    let a = chamfer_at(fu, fv, s.edge) * (1.0 + s.grain * n.g + 0.06 * n.voxel + s.patch * n.p);
    // Оттенок: воксель и пятно уходят к тёплому или холодному полюсу
    // класса. Знак берёт воксель, силу — пятно: так пятна одного
    // оттенка складываются из вокселей, а не рассыпаются по одному.
    let t = (0.6 * n.voxel + 0.4 * n.p).clamp(-1.0, 1.0);
    let (warm, cool) = hue_axis(c);
    let pole = if t >= 0.0 { warm } else { cool };
    let k = t.abs() * s.hue;
    let mut rgb = pole.map(|p| a * (1.0 + (p - 1.0) * k));
    if n.speck {
        for (c, m) in rgb.iter_mut().zip(s.speck_srgb) {
            *c *= m;
        }
    }
    rgb.map(|c| c.clamp(0.0, 1.0))
}

/// Свойства поверхности в точке плитки: затенение, шероховатость,
/// металличность — каналы `R`, `G`, `B`, как их читает
/// `StandardMaterial` (`occlusion_texture` и `metallic_roughness_texture`).
/// Линейные, 0..1; материал ставит свои множители на единицу, и то,
/// что здесь, и есть значение.
fn props_at(l: Look, c: Class, u: f32, v: f32) -> [f32; 3] {
    let s = surf_of(l, c);
    let (vx, vz, fu, fv) = split(u, v);
    let n = grain_at(&s, vx, vz, fu, fv);
    // Шероховатость плитка только снимает: скол и пятно глаже
    // матовой основы, а грубее её не бывает.
    let smooth = (0.5 + 0.5 * (0.7 * n.g + 0.3 * n.p)).clamp(0.0, 1.0);
    let mut rough = s.rough * (1.0 - s.rough_var * smooth);
    let mut metal = s.metal * s.matrix_metal;
    if n.speck {
        // Вкрапление — это и есть пик: металл целиком, блеск
        // крупинки. У земли и породы металла нет, и крупинка там
        // только глаже.
        rough = s.rough * (1.0 - s.rough_var) * 0.6;
        metal = s.metal;
    }
    // Щель между вокселями темнее в рассеянном свете: половина фаски
    // уходит в затенение, чтобы ребро держалось и в тени, где
    // цветовую плитку уже не видно.
    let occ = 1.0 - 0.5 * (1.0 - chamfer_at(fu, fv, s.edge).min(1.0));
    [
        occ.clamp(0.0, 1.0),
        rough.clamp(0.04, 1.0),
        metal.clamp(0.0, 1.0),
    ]
}

/// Касательная нормаль в точке плитки. Единичная, `z` наружу.
fn normal_at(l: Look, c: Class, u: f32, v: f32) -> [f32; 3] {
    let s = surf_of(l, c);
    let (vx, vz, fu, fv) = split(u, v);
    // Выгиб: наклон растёт к краю воксела и на самом краю обнуляется,
    // иначе на стыке двух вокселей нормаль прыгает и шов виден полосой.
    let bend = |t: f32| -> f32 {
        let x = t * 2.0 - 1.0;
        x * (1.0 - x * x)
    };
    let mut nx = -s.dome * bend(fu);
    let mut ny = -s.dome * bend(fv);
    let salt = vx.wrapping_mul(73).wrapping_add(vz.wrapping_mul(9173));
    let (gu, gv) = ((fu * s.cells).floor() as i64, (fv * s.cells).floor() as i64);
    nx += s.bump * cell_hash(gu, gv, salt ^ 0x0B1);
    ny += s.bump * cell_hash(gu, gv, salt ^ 0x0B2);
    let len = (nx * nx + ny * ny + 1.0).sqrt();
    [nx / len, ny / len, 1.0 / len]
}

/// Цветовая плитка класса со всеми уровнями. **sRGB**: это цвет.
pub fn surface_tile(c: Class) -> Tile {
    surface_tile_of(active(), c)
}

/// То же для заданного направления.
pub fn surface_tile_of(l: Look, c: Class) -> Tile {
    // Цвет считается в sRGB, усредняется по уровням в линейном
    // и кодируется обратно: усреднить sRGB напрямую значит осветлить
    // каждый следующий уровень, и рельеф вдали стал бы светлее,
    // чем вблизи.
    build_tile(
        |u, v| {
            let s = albedo_at(l, c, u, v);
            [srgb_to_lin(s[0]), srgb_to_lin(s[1]), srgb_to_lin(s[2])]
        },
        lin_to_srgb,
    )
}

/// Плитка свойств класса: затенение, шероховатость, металличность
/// в `R`, `G`, `B`. **Линейная**: это числа, а не цвет.
pub fn props_tile(c: Class) -> Tile {
    props_tile_of(active(), c)
}

/// То же для заданного направления.
pub fn props_tile_of(l: Look, c: Class) -> Tile {
    build_tile(|u, v| props_at(l, c, u, v), |x| x)
}

/// Плитка из функции точки со всеми уровнями детализации.
///
/// `px` даёт **линейное** значение трёх каналов; уровни усредняются
/// в нём же, и только байты кодируются через `encode`.
pub(crate) fn build_tile(mut px: impl FnMut(f32, f32) -> [f32; 3], encode: fn(f32) -> f32) -> Tile {
    let n = TILE as usize;
    let mut cur: Vec<[f32; 3]> = vec![[0.0; 3]; n * n];
    for y in 0..n {
        for x in 0..n {
            // Центр пикселя, а не угол: с углом плитка получается
            // на полпикселя сдвинутой и швы на стыке не сходятся.
            let u = (x as f32 + 0.5) / TILE as f32;
            let v = (y as f32 + 0.5) / TILE as f32;
            cur[y * n + x] = px(u, v);
        }
    }
    let mut rgba = Vec::new();
    let mut mips = 0u32;
    let mut cs = n;
    loop {
        push_level(&cur, cs, encode, &mut rgba);
        mips += 1;
        if cs == 1 {
            break;
        }
        let ns = cs / 2;
        let mut next = vec![[0.0f32; 3]; ns * ns];
        for y in 0..ns {
            for x in 0..ns {
                let i = |yy: usize, xx: usize| cur[yy * cs + xx];
                let mut a = [0.0f32; 3];
                for q in [
                    i(2 * y, 2 * x),
                    i(2 * y, 2 * x + 1),
                    i(2 * y + 1, 2 * x),
                    i(2 * y + 1, 2 * x + 1),
                ] {
                    for k in 0..3 {
                        a[k] += q[k] * 0.25;
                    }
                }
                next[y * ns + x] = a;
            }
        }
        cur = next;
        cs = ns;
    }
    Tile {
        size: TILE,
        mips,
        rgba,
    }
}

/// Плитка нормалей класса. **Линейная**, не sRGB: это вектор,
/// а не цвет, и гамма его искривит.
pub fn normal_tile(c: Class) -> Tile {
    normal_tile_of(active(), c)
}

/// То же для заданного направления.
pub fn normal_tile_of(l: Look, c: Class) -> Tile {
    build_normal_tile(|u, v| normal_at(l, c, u, v))
}

pub(crate) fn build_normal_tile(px: impl Fn(f32, f32) -> [f32; 3]) -> Tile {
    let n = TILE as usize;
    let mut cur: Vec<[f32; 3]> = vec![[0.0; 3]; n * n];
    for y in 0..n {
        for x in 0..n {
            let u = (x as f32 + 0.5) / TILE as f32;
            let v = (y as f32 + 0.5) / TILE as f32;
            cur[y * n + x] = px(u, v);
        }
    }
    let mut rgba = Vec::new();
    let mut mips = 0u32;
    let mut cs = n;
    loop {
        push_normal_level(&cur, cs, &mut rgba);
        mips += 1;
        if cs == 1 {
            break;
        }
        let ns = cs / 2;
        let mut next = vec![[0.0f32; 3]; ns * ns];
        for y in 0..ns {
            for x in 0..ns {
                let i = |yy: usize, xx: usize| cur[yy * cs + xx];
                let mut a = [0.0f32; 3];
                for q in [
                    i(2 * y, 2 * x),
                    i(2 * y, 2 * x + 1),
                    i(2 * y + 1, 2 * x),
                    i(2 * y + 1, 2 * x + 1),
                ] {
                    for k in 0..3 {
                        a[k] += q[k] * 0.25;
                    }
                }
                // Усреднённые векторы **перенормируются**: сумма
                // единичных единичной не бывает, и без этого дальние
                // уровни светили бы иначе, чем ближние.
                let l = (a[0] * a[0] + a[1] * a[1] + a[2] * a[2]).sqrt().max(1e-6);
                next[y * ns + x] = [a[0] / l, a[1] / l, a[2] / l];
            }
        }
        cur = next;
        cs = ns;
    }
    Tile {
        size: TILE,
        mips,
        rgba,
    }
}

/// Уровень из нормалей — в байты, со сдвигом из −1..1 в 0..1.
fn push_normal_level(v: &[[f32; 3]], n: usize, out: &mut Vec<u8>) {
    out.reserve(n * n * 4);
    for q in v.iter().take(n * n) {
        let b = |x: f32| ((x * 0.5 + 0.5) * 255.0 + 0.5).clamp(0.0, 255.0) as u8;
        out.extend_from_slice(&[b(q[0]), b(q[1]), b(q[2]), 255]);
    }
}

/// Уровень из линейных троек — в байты, через `encode` по каналу.
fn push_level(lin: &[[f32; 3]], n: usize, encode: fn(f32) -> f32, out: &mut Vec<u8>) {
    out.reserve(n * n * 4);
    for q in lin.iter().take(n * n) {
        let b = |x: f32| (encode(x) * 255.0 + 0.5).clamp(0.0, 255.0) as u8;
        out.extend_from_slice(&[b(q[0]), b(q[1]), b(q[2]), 255]);
    }
}

fn srgb_to_lin(u: f32) -> f32 {
    if u <= 0.04045 {
        u / 12.92
    } else {
        ((u + 0.055) / 1.055).powf(2.4)
    }
}

fn lin_to_srgb(u: f32) -> f32 {
    if u <= 0.003_130_8 {
        u * 12.92
    } else {
        1.055 * u.powf(1.0 / 2.4) - 0.055
    }
}

// --- Свет, небо, атмосфера -------------------------------------------
//
// Небо у нас **процедурное**: `bevy_pbr::atmosphere` считает рассеяние
// и из одного положения солнца выдаёт разом цвет неба, цвет света
// у земли, дымку по глубине и карту окружения для отражений. Плоская
// заливка и три подобранных на глаз источника заменены одним числом —
// высотой солнца (ADR-198).

/// Куда светит солнце, в мировых осях.
///
/// Функция, а не константа: `sin`/`cos` в `const fn` нет, а держать
/// вектор и углы порознь значит рассинхронизировать их при первой же
/// правке.
pub fn sun_dir() -> [f32; 3] {
    let s = scene();
    sun_dir_at(s.sun_elevation, s.sun_azimuth)
}

/// То же для произвольного времени суток: высота и азимут в радианах.
///
/// Вектор нормирован по построению, и это важнее, чем кажется:
/// `looking_to` с ненормированным направлением даёт масштаб в матрице
/// поворота света.
pub fn sun_dir_at(elevation: f32, azimuth: f32) -> [f32; 3] {
    let (se, ce) = (elevation.sin(), elevation.cos());
    let (sa, ca) = (azimuth.sin(), azimuth.cos());
    [-ce * sa, -se, -ce * ca]
}

