    /// **Уровни усреднены в линейном пространстве, а не в sRGB.**
    ///
    /// Единственный пиксель последнего уровня обязан совпасть
    /// с линейным средним всей плитки. Усреднение прямо в байтах sRGB
    /// даёт заметно светлее — и поверхность вдали становится светлее,
    /// чем вблизи, плавно и незаметно.
    #[test]
    fn the_mips_are_averaged_in_linear_light() {
        for l in LOOK_ALL {
            for c in [Class::Soil, Class::Rock, Class::Ore] {
                let n = TILE as usize;
                let mut sum = [0.0f64; 3];
                for y in 0..n {
                    for x in 0..n {
                        let u = (x as f32 + 0.5) / TILE as f32;
                        let v = (y as f32 + 0.5) / TILE as f32;
                        let s = albedo_at(l, c, u, v);
                        for (acc, ch) in sum.iter_mut().zip(s) {
                            *acc += srgb_to_lin(ch) as f64;
                        }
                    }
                }
                let t = surface_tile_of(l, c);
                for (k, total) in sum.iter().enumerate() {
                    let want = (lin_to_srgb((total / (n * n) as f64) as f32) * 255.0 + 0.5) as i32;
                    let got = t.rgba[t.rgba.len() - 4 + k] as i32;
                    assert!(
                        (got - want).abs() <= 1,
                        "мельчайший уровень {got}, ждали {want}"
                    );
                    assert!(got < 255, "плитка не темнеет вовсе");
                }
            }
        }
    }

    /// **Плитка цветная там, где направление этого просит, и серая,
    /// где нет.** Оттенок — отклонение от цвета вершины: в среднем
    /// по плитке он обязан почти гаснуть, иначе материал перекрашен,
    /// а не оживлён.
    #[test]
    fn the_tile_carries_hue_but_stays_neutral_on_average() {
        for l in LOOK_ALL {
            let t = surface_tile_of(l, Class::Soil);
            let n = (TILE * TILE) as usize;
            let (mut coloured, mut r, mut b) = (0usize, 0.0f64, 0.0f64);
            for p in t.rgba[..n * 4].chunks(4) {
                if p[0] != p[2] {
                    coloured += 1;
                }
                r += p[0] as f64;
                b += p[2] as f64;
            }
            let hue = surf_of(l, Class::Soil).hue;
            assert!(
                (hue > 0.0) == (coloured > n / 10),
                "{}: оттенок {hue}, а цветных пикселей {coloured} из {n}",
                look_name(l)
            );
            // Среднее не уезжает: тёплые и холодные воксели друг друга
            // уравновешивают.
            assert!(
                (r - b).abs() / (n as f64) < 6.0,
                "{}: плитка в среднем цветная",
                look_name(l)
            );
        }
    }

    /// **Металл руды — в крупинках, а не в грани.** Плитка свойств
    /// обязана нести полную металличность лишь в доле пикселей,
    /// а у земли металла нет нигде.
    #[test]
    fn the_metal_of_ore_sits_in_the_specks() {
        for l in LOOK_ALL {
            let n = (TILE * TILE) as usize;
            let ore = props_tile_of(l, Class::Ore);
            let peak = ore.rgba[..n * 4].chunks(4).filter(|p| p[2] >= 200).count();
            let s = surf_of(l, Class::Ore);
            if s.matrix_metal < 0.9 {
                assert!(
                    peak > n / 100,
                    "{}: металл руды нигде не пиковый",
                    look_name(l)
                );
                assert!(peak < n / 2, "{}: руда металлическая целиком", look_name(l));
            }
            let soil = props_tile_of(l, Class::Soil);
            assert!(
                soil.rgba[..n * 4].chunks(4).all(|p| p[2] < 40),
                "{}: земля металлическая",
                look_name(l)
            );
            // Шероховатость не выше своей: плитка только снимает её.
            let rough_max =
                ore.rgba[..n * 4].chunks(4).map(|p| p[1]).max().unwrap_or(0) as f32 / 255.0;
            assert!(
                rough_max <= s.rough + 0.01,
                "{}: плитка грубее класса",
                look_name(l)
            );
        }
    }

    /// **Склон — другого цвета, а не только другой яркости**, там, где
    /// направление это задаёт; у графики склон отличается ровно
    /// ступенью яркости, и ничем больше.
    #[test]
    fn the_slope_differs_from_the_top_by_hue_where_asked() {
        for l in LOOK_ALL {
            let s = surf_of(l, Class::Soil).side;
            let c = palette_srgb(l, 0);
            let top = to_linear(c);
            let side = to_linear([c[0] * s[0], c[1] * s[1], c[2] * s[2]]);
            let ratio = |a: [f32; 4]| a[0] / a[2].max(1e-4);
            let shifted = (ratio(top) - ratio(side)).abs() > 0.02;
            assert_eq!(shifted, s != [1.0; 3], "{}: склон и верх", look_name(l));
        }
        // И таблица склона считается из того же числа. Направление
        // здесь не переключается: тесты идут параллельно, и раскраска
        // из `geom` читает то же глобальное направление.
        let t = &tables()[Look::Vangers as usize];
        assert_ne!(
            t.colour[1], t.side[1],
            "у Вангеров склон не отличается от верха"
        );
        let s = colour_side(1);
        assert_eq!(colour_face(1, 0, true)[0], s[0] * face_steps(active())[1]);
        assert_eq!(
            colour_face(1, 1, true),
            colour(1),
            "верх красится не цветом материала"
        );
    }

    /// **Пятна сходятся на краю плитки.** Плитка повторяется каждые
    /// `TILE_VOXELS` вокселей, и разрыв шума на её границе был бы
    /// сеткой через весь рельеф.
    #[test]
    fn the_patches_wrap_around_the_tile() {
        let n = TILE_VOXELS as i64;
        for (n, salt) in [(n / 4, 0x9A7i64), (n / 2, 0x9A8)] {
            for t in 0..17 {
                let v = t as f32 / 16.0;
                let (a, b) = (patch_at(0.0005, v, n, salt), patch_at(0.9995, v, n, salt));
                assert!((a - b).abs() < 0.02, "разрыв {a} против {b} при v={v}");
                let (a, b) = (patch_at(v, 0.0005, n, salt), patch_at(v, 0.9995, n, salt));
                assert!((a - b).abs() < 0.02, "разрыв {a} против {b} при u={v}");
            }
        }
    }

    /// **Нормали в мельчайшем уровне тоже единичные.** Среднее четырёх
    /// единичных векторов короче единицы, и без перенормировки дальний
    /// рельеф светил бы иначе, чем ближний.
    #[test]
    fn the_smallest_normal_level_is_still_unit_length() {
        for l in LOOK_ALL {
            for c in [Class::Soil, Class::Rock, Class::Ore] {
                let t = normal_tile_of(l, c);
                let k = t.rgba.len() - 4;
                let v = |i: usize| t.rgba[k + i] as f32 / 255.0 * 2.0 - 1.0;
                let len = (v(0) * v(0) + v(1) * v(1) + v(2) * v(2)).sqrt();
                assert!((len - 1.0).abs() < 0.01, "длина {len} в мельчайшем уровне");
            }
        }
    }
