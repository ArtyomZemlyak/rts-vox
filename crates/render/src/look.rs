pub const AMBIENT_SRGB: [f32; 3] = [0.58, 0.67, 0.82];
pub const AMBIENT_BRIGHTNESS: f32 = 40.0;

/// Небо за краем мира на случай, когда атмосферы нет. При работающей
/// атмосфере этот цвет не виден ни в одном пикселе.
pub const SKY_COLOUR_SRGB: [f32; 3] = [0.56, 0.69, 0.86];

/// Сколько метров атмосферы приходится на один воксель мира.
///
/// **Это ручка глубины, а не единица измерения.** Воксель мира — 0.5 м
/// (ADR-094), и на честном масштабе вся карта укладывается в двести
