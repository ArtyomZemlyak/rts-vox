//! Числа картинки: свет, небо, палитра материалов.
//!
//! **Это не игровые числа.** Цвет породы и яркость солнца не меняют ни
//! одного исхода и в хеш состояния не входят, поэтому им не место
//! в `data/*.ron` рядом со стоимостью и уроном. Но и рассыпать их по
//! коду нельзя: подобранная картинка — это дюжина чисел, которые
//! обязаны меняться вместе, иначе подбор превращается в поиск по файлам.
//!
//! Плавающая точка здесь разрешена — рендер в хеш не входит
//! (`docs/03-determinism.md`).

use voxel::store::Mat;

/// sRGB → линейный.
///
/// Нужна не для красоты: цвет вершины в Bevy 0.19.1 **подменяет**
/// `base_color` материала (`pbr_fragment.wgsl`), а `base_color`
/// линейный. Положить туда sRGB — значит осветлить всё примерно
/// в два раза и не понять почему.
pub fn to_linear(c: [f32; 3]) -> [f32; 4] {
    let f = |u: f32| {
        if u <= 0.04045 {
            u / 12.92
        } else {
            ((u + 0.055) / 1.055).powf(2.4)
        }
    };
    [f(c[0]), f(c[1]), f(c[2]), 1.0]
}

/// Как рисуется материал мира.
///
/// Шероховатость и металличность **не могут** быть свойством вершины:
/// у `StandardMaterial` их читает материал, а не меш. Поэтому вместо
/// числа здесь класс, и на класс приходится по одному материалу Bevy.
/// Классов ровно два: иначе на чанк пришлось бы по вызову отрисовки
/// на каждый материал, а материалов в паке одиннадцать.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[repr(u8)]
pub enum Class {
    /// Грунт и порода: шероховатый диэлектрик.
    Rock = 0,
    /// Руда: гладкая и металлическая, поэтому и видно, где копать.
    Ore = 1,
}

/// Сколько классов — столько мешей на чанк.
pub const CLASSES: usize = 2;

/// Цвет и класс материала. Номер явный, как в `data/materials.ron`
/// (ADR-028): вывести его из позиции в списке — значит перекрасить
/// весь мир, переставив строку.
struct MatLook {
    id: Mat,
    srgb: [f32; 3],
    class: Class,
}

/// Палитра ванильного пака. Номера — из `data/materials.ron`.
///
/// Цвета живут здесь, а не в паке материалов: добавить их в пак значит
/// расширить контракт мод-API, а это отдельное решение. Пока мод,
/// принёсший свой материал, получает цвет по умолчанию.
const PALETTE: &[MatLook] = &[
    MatLook { id: 1, srgb: [0.47, 0.37, 0.24], class: Class::Rock }, // почва
    MatLook { id: 2, srgb: [0.47, 0.47, 0.49], class: Class::Rock }, // порода
    MatLook { id: 3, srgb: [0.29, 0.31, 0.36], class: Class::Rock }, // глубинная
    MatLook { id: 16, srgb: [0.52, 0.40, 0.31], class: Class::Ore }, // железо бедное
    MatLook { id: 17, srgb: [0.68, 0.47, 0.30], class: Class::Ore }, // железо
    MatLook { id: 18, srgb: [0.85, 0.55, 0.27], class: Class::Ore }, // железо богатое
    MatLook { id: 24, srgb: [0.33, 0.47, 0.44], class: Class::Ore }, // медь бедная
    MatLook { id: 25, srgb: [0.25, 0.62, 0.55], class: Class::Ore }, // медь
    MatLook { id: 26, srgb: [0.20, 0.78, 0.63], class: Class::Ore }, // медь богатая
    MatLook { id: 40, srgb: [1.00, 0.42, 0.10], class: Class::Ore }, // лава
];

/// Цвет неизвестного материала: мод принёс свой номер, а цвета для него
/// нет. Кричащая фуксия лучше тихого серого — её видно на скриншоте.
const UNKNOWN: [f32; 3] = [0.85, 0.15, 0.70];

/// Перебор палитры. Горячий путь им не пользуется — там таблица ниже,
/// — а тестам нужен именно «есть ли такой номер вообще».
#[cfg(test)]
fn look(m: Mat) -> Option<&'static MatLook> {
    PALETTE.iter().find(|e| e.id == m)
}

/// Готовые ответы по номеру материала.
///
/// Не преждевременная оптимизация, а замер: `colour` зовётся **на
/// каждый выпущенный квад**, а внутри у него был перебор палитры и три
/// `powf`. На чанке это тысячи вызовов, и в кадре они стоили дороже
/// всего остального в раскраске вместе (ADR-175).
///
/// Двести пятьдесят шесть — потолок номера материала у мешера
/// (`materials_present`), так что таблица покрывает всё, что может
/// прийти.
struct Tables {
    colour: [[f32; 4]; 256],
    class: [Class; 256],
}

fn tables() -> &'static Tables {
    static T: std::sync::OnceLock<Tables> = std::sync::OnceLock::new();
    T.get_or_init(|| {
        let mut t = Tables {
            colour: [to_linear(UNKNOWN); 256],
            class: [Class::Rock; 256],
        };
        for e in PALETTE {
            let i = e.id as usize;
            t.colour[i] = to_linear(e.srgb);
            t.class[i] = e.class;
        }
        t
    })
}

/// Класс материала: он же номер меша чанка.
pub fn class(m: Mat) -> Class {
    tables().class[(m as usize).min(255)]
}

/// Линейный цвет вершины для материала.
pub fn colour(m: Mat) -> [f32; 4] {
    tables().colour[(m as usize).min(255)]
}

/// Шероховатость и металличность класса — то, что не влезло в вершину.
pub fn surface(c: Class) -> (f32, f32) {
    match c {
        // Порода матовая: блик на ней читается как мокрое пятно.
        Class::Rock => (0.92, 0.0),
        // Руда наполовину металлическая: полный металл без карты
        // окружения выходит чёрным, потому что отражать нечего.
        Class::Ore => (0.38, 0.55),
    }
}

/// Цвет стороны: им красится броня, по нему юнита и узнают.
pub const SIDE_TINT: [[f32; 3]; 2] = [[0.30, 0.52, 0.80], [0.86, 0.45, 0.16]];

/// Цвет роли воксела. Броня берёт цвет стороны, остальное — своё.
pub fn part_srgb(p: voxel::unit::Part, tint: [f32; 3]) -> [f32; 3] {
    use voxel::unit::Part;
    match p {
        Part::Armour => tint,
        // Орудие тёмное: ствол обязан читаться на фоне корпуса.
        Part::Weapon => [0.18, 0.18, 0.20],
        Part::Engine => [0.34, 0.26, 0.16],
        Part::Sensor => [0.88, 0.92, 0.96],
        // Ядро внутри и снаружи не видно; цвет на случай, когда броню
        // вокруг него снесли.
        Part::Core => [1.00, 0.83, 0.22],
    }
}

// --- Свет и небо -----------------------------------------------------
//
// Схема из трёх источников, и третий здесь не роскошь. Одно солнце
// с тенями даёт чёрную теневую сторону: заполнять её нечем, карты
// окружения у нас нет. Заполняющий свет сверху-сзади даёт этой стороне
// **направление**, а ровный ambient — только уровень.

/// Солнце: тёплое, с тенями.
pub const SUN_SRGB: [f32; 3] = [1.0, 0.94, 0.82];
/// Люксы. Дневной свет у Bevy — 10 000; берём чуть выше, потому что
/// тонмаппинг съедает верх.
pub const SUN_LUX: f32 = 13_000.0;
/// Куда светит солнце, в мировых осях. Не в зенит: тени в зените
/// не видно, а форму рельефа читает именно длинная тень.
pub const SUN_DIR: [f32; 3] = [-0.45, -0.72, -0.52];

/// Заполняющий свет неба: холодный, слабый, **без теней**.
pub const SKY_SRGB: [f32; 3] = [0.62, 0.74, 1.0];
pub const SKY_LUX: f32 = 2_600.0;
pub const SKY_DIR: [f32; 3] = [0.38, -0.55, 0.62];

/// Ровный фон, чтобы совсем закрытые щели не проваливались в ноль.
pub const AMBIENT_SRGB: [f32; 3] = [0.58, 0.67, 0.82];
pub const AMBIENT_BRIGHTNESS: f32 = 260.0;

/// Небо за краем мира. Оно же цвет тумана: если они разойдутся,
/// на горизонте появится полоса.
pub const SKY_COLOUR_SRGB: [f32; 3] = [0.56, 0.69, 0.86];

/// Туман по глубине, в мировых вокселях. Задаёт масштаб: без него
/// дальний край карты и ближний строй отличаются только размером.
///
/// Доли от стороны мира, а не абсолютные числа: мир показа меняется
/// ключом `--side`, и туман обязан ехать вместе с ним.
pub const FOG_START_FRAC: f32 = 0.35;
pub const FOG_END_FRAC: f32 = 1.15;

/// Тени: сколько каскадов и докуда. Доли от стороны мира по той же
/// причине, что у тумана.
pub const SHADOW_CASCADES: usize = 3;
pub const SHADOW_FIRST_FRAC: f32 = 0.10;
pub const SHADOW_MAX_FRAC: f32 = 0.70;
/// Щелевое затенение включено по умолчанию или нет. Решается замером,
