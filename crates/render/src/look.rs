/// Весь набор чисел картинки одного направления.
///
/// Структура, а не россыпь констант: направление переключается целиком,
/// и половина набора от одного с половиной от другого не даёт третьего.
#[derive(Clone, Copy, PartialEq, Debug)]
pub struct Scene {
    /// Высота солнца над горизонтом, радианы. **Главное число
    /// картинки.** В зените тени не видно, и рельеф читается как
    /// заливка; у горизонта тень длинная, свет тёплый, а теневой
    /// стороне достаётся голубизна неба.
    pub sun_elevation: f32,
    /// Азимут солнца, радианы: поворот источника вокруг вертикали.
    ///
    /// Он же решает, **контровой** свет или боковой: солнце напротив
    /// камеры (азимут ≈ `yaw` камеры плюс π) даёт кайму по силуэту
    /// и длинную тень в кадр.
    pub sun_azimuth: f32,
    /// Солнце белое, а не тёплое.
    ///
    /// Тёплым его делает атмосфера: у горизонта синева рассеивается
    /// сильнее красного. Подкрасить источник руками значит покрасить
    /// дважды, и на закате получить оранжевое вдвое.
    pub sun_srgb: [f32; 3],
    /// Люксы **до** атмосферы. Именно это число ждёт рассеяние
    /// на входе: 10 000 у Bevy — уже отфильтрованный воздухом дневной
    /// свет, и подать его сюда значит отфильтровать второй раз.
    pub sun_lux: f32,
    /// Диск солнца в небе: угловой размер в радианах и яркость.
    ///
    /// Земной диск (0.0093 рад) на кадре RTS — несколько пикселей.
    /// Берём крупнее: солнце здесь опора композиции, а не астрономия.
    pub sun_disk_size: f32,
    pub sun_disk_intensity: f32,
    /// Множитель поглощения дыма при отрисовке газа (ADR-283): единица —
    /// плотность до решения, меньше — облако прозрачнее, и бой читается
    /// сквозь его края.
    pub smoke_extinction: f32,
    /// Множитель остаточного свечения прогретой земли после фугаса в
    /// проходе газа (ADR-298): единица — как было, ноль — нет.
    pub ground_glow: f32,

    /// Экспозиция камеры, EV100. Держится в паре с `sun_lux`: яркость
    /// источника и экспозиция — одна настройка, разнесённая по двум
    /// компонентам, и менять их порознь нельзя.
    pub ev100: f32,
    pub tonemap: Tonemap,
    pub grade: Grade,
    pub vignette: Vignette,
    /// Сила свечения. Ноль — свечения нет вовсе.
    pub bloom: f32,
    /// Диафрагма для глубины резкости, в стопах. Ноль — резко всё.
    /// Малое число размывает сильнее: это знаменатель.
    ///
    /// **Не украшение, а единственный честный признак макета.** Глаз
    /// читает малую глубину резкости как «снято вблизи», то есть как
    /// «вещь маленькая», — и ничем другим этого не сказать.
    pub dof_f_stops: f32,

    /// Яркость карты окружения, снятой с неба. Она же весь заполняющий
    /// свет: отдельный «свет неба» и ровный ambient не нужны, когда
    /// небо есть на самом деле.
    ///
    /// Больше единицы намеренно. Физически верное значение — ровно
    /// единица, и при низком солнце оно даёт теневой стороне строя
    /// почти чёрный: по картинке красиво, по игре — половину войска
    /// не видно.
    pub sky_ibl: f32,
    /// Сторона кубкарты окружения. Отражения у нас размытые, деталей
    /// в них не читается, а пересчёт идёт каждый кадр.
    pub sky_ibl_size: u32,
    /// Ровный фон — страховка, а не свет. Атмосфера требует
    /// вычислительных шейдеров, и на машине без них её плагин молча
    /// не загрузится; без этих единиц сцена там стала бы чёрной
    /// с теневой стороны.
    pub ambient_srgb: [f32; 3],
    pub ambient_brightness: f32,
    /// Небо за краем мира на случай, когда атмосферы нет. При
    /// работающей атмосфере этот цвет не виден ни в одном пикселе.
    pub sky_colour_srgb: [f32; 3],

    /// Сколько метров атмосферы приходится на один воксель мира.
    ///
    /// **Это ручка глубины, а не единица измерения.** Воксель мира —
    /// 0.5 м (ADR-094), и на честном масштабе вся карта укладывается
    /// в двести метров, где рассеяния нет вовсе: дальний край и ближний
    /// строй отличались бы только размером. Растянутая атмосфера даёт
    /// дымку, **согласованную с небом по построению** — при любом
    /// положении солнца.
    pub haze_metres_per_voxel: f32,
    /// Докуда считается дымка, в метрах атмосферы. Меньше — быстрее,
    /// но дальше этого рубежа глубина перестаёт читаться.
    pub haze_range_m: f32,

    /// Тени: сколько каскадов и докуда. Доли от стороны мира, а не
    /// абсолютные числа: мир показа меняется ключом `--side`,
    /// и дальности обязаны ехать вместе с ним.
    pub shadow_cascades: usize,
    pub shadow_first_frac: f32,
    pub shadow_max_frac: f32,
    /// Сторона карты теней. Степень двойки — иначе Bevy её округлит
    /// сам и предупредит.
    pub shadow_map: usize,
    /// Щелевое затенение. Оно снимает сглаживание по подвыборкам,
    /// и сдачу приходится добирать FXAA; направлению с плоской тенью
    /// оно к тому же мешает — мягкая грязь в углах ровно там, где
    /// нужно чистое пятно.
    pub ssao: bool,
    /// Толщина предмета для щелевого затенения, мировые единицы:
    /// докуда за поверхностью луч считается перекрытым. Радиус самого
    /// эффекта у Bevy зашит в шейдер (`0.5 · 1.457` единицы), и при
    /// ребре мира в десять сантиметров это семь сантиметров — щели
    /// рельефа он не читает; толщина — единственная ручка, что есть.
    pub ssao_thickness: f32,
    /// Сглаживание по морфологии (SMAA) вместо FXAA. Прямые рёбра
    /// вокселей — ровно тот случай, где FXAA мылит, а SMAA нет.
    pub smaa: bool,
    /// Объёмный туман: воздух, который видно, и лучи от солнца.
    pub fog: Fog,
    /// Щелевое затенение по вокселям — свой проход с радиусом
    /// в вокселях мира.
    pub occlusion: Occl,
    /// Обводка силуэта и ступени яркости — отдельный проход
    /// по глубине и нормалям.
    pub edge: Edge,
}

/// Щелевое затенение по вокселям: постпроцесс по глубине и нормалям
/// (`render::occlusion`, ADR-235).
///
/// Щелевое затенение Bevy до воксельных щелей не достаёт: радиус
/// у него зашит в шейдере — семь сантиметров при ребре мира 10 см.
/// Здесь радиус свой, и меряется он в вокселях мира: воронка,
/// подножие обрыва и щель между машиной и землёй лежат на масштабе
/// в несколько вокселей.
#[derive(Clone, Copy, PartialEq, Debug)]
pub struct Occl {
    /// Радиус полусферы выборок, воксели мира. Ноль — прохода нет.
    pub radius: f32,
    /// Сила затемнения, 0..1. Ноль — прохода нет.
    pub strength: f32,
    /// Смещение по глубине против самозатенения, воксели мира.
    pub bias: f32,
    /// Степень кривой: больше — тень собирается в самой щели.
    pub power: f32,
}

impl Occl {
    pub const NONE: Occl = Occl {
        radius: 0.0,
        strength: 0.0,
        bias: 0.1,
        power: 1.0,
    };

    /// Есть ли что ставить на камеру.
    pub fn on(&self) -> bool {
        self.radius > 0.0 && self.strength > 0.0
    }
}

/// Объёмный туман (ADR-235). Плотность ноль — тумана нет, и проход
/// не ставится вовсе. **Ни одно направление его не включает**: на
/// плотности, где он виден, кадр тонет в мути, а на плотности,
/// где мути нет, его не видно; числа оставлены ручкой `--fog`
/// окна боя для проб.
///
/// Это не дымка по глубине: ту даёт атмосфера, и она про дальний план.
/// Объёмный туман — про **близкий** воздух: столбы света между
/// холмами на контровом солнце и тень машины в воздухе, а не только
/// на земле.
#[derive(Clone, Copy, PartialEq, Debug)]
pub struct Fog {
    /// Плотность: сколько света воздух рассеивает на единице пути.
    pub density: f32,
    /// Доля поглощённого света на шаге. Больше — туман темнее.
    pub absorption: f32,
    /// Доля рассеянного к зрителю света на шаге.
    pub scattering: f32,
    /// Яркость света неба в тумане: без неё туман светится только
    /// там, куда попадает солнце, и в тени он чёрный.
    pub ambient: f32,
    /// Высота слоя тумана в долях стороны мира, от пола мира.
    pub height: f32,
    /// Шагов марша на пиксель. Меньше — полосы, больше — дороже.
    pub steps: u32,
}

impl Fog {
    pub const NONE: Fog = Fog {
        density: 0.0,
        absorption: 0.3,
        scattering: 0.3,
        ambient: 0.1,
        height: 0.5,
        steps: 32,
    };
}

/// Набор чисел выбранного направления.
pub fn scene() -> Scene {
    SCENE_OVERRIDE
        .read()
        .ok()
        .and_then(|o| *o)
        .unwrap_or_else(|| scene_of(active()))
}
/// Числа картинки, выкрученные вживую (ADR-298); `None` — стоковые.
pub fn override_scene(s: Option<Scene>) {
    if let Ok(mut slot) = SCENE_OVERRIDE.write() {
        *slot = s;
    }
}
static SCENE_OVERRIDE: std::sync::RwLock<Option<Scene>> = std::sync::RwLock::new(None);

/// Набор чисел заданного направления.
pub fn scene_of(l: Look) -> Scene {
    // Базовое направление — то, что было до ADR-214. Остальные три
    // записаны от него отличиями, и отличия эти перечислены
    // в `docs/analysis/10-decisions-full.md`.
    let base = Scene {
        sun_elevation: 0.33,
        sun_azimuth: -0.75,
        sun_srgb: [1.0, 1.0, 1.0],
        sun_lux: 130_000.0,
        sun_disk_size: 0.028,
        sun_disk_intensity: 1.0,
        smoke_extinction: 0.55,
        ground_glow: 0.35,
        ev100: 13.1,
        tonemap: Tonemap::Aces,
        grade: Grade::NEUTRAL,
        vignette: Vignette::NONE,
        bloom: 0.15,
        dof_f_stops: 0.0,
        sky_ibl: 1.7,
        sky_ibl_size: 128,
        ambient_srgb: [0.58, 0.67, 0.82],
        ambient_brightness: 40.0,
        sky_colour_srgb: [0.56, 0.69, 0.86],
        // Числа дымки подобраны на ребре мира в полметра (ADR-198,
        // ADR-214) и здесь **разделены на пять**: ребро стало десять
        // сантиметров (`voxel::unit::WORLD_MM`), а растяжение атмосферы
        // — это ручка глубины на воксель, и на прежнем числе камера
        // висела в трёх километрах над картой в тридцать восемь метров,
        // и вся сцена тонула в сером (ADR-235).
        haze_metres_per_voxel: 3.6,
        haze_range_m: 24_000.0,
        shadow_cascades: 4,
        shadow_first_frac: 0.07,
        shadow_max_frac: 0.85,
        shadow_map: 4096,
        ssao: true,
        ssao_thickness: 0.25,
        smaa: false,
        fog: Fog::NONE,
        occlusion: Occl::NONE,
        edge: Edge::NONE,
    };
    match l {
        Look::Base => base,

        // Диорама. Солнце **напротив камеры** (при `--yaw 0.7`
        // умолчания окна): контровой свет ставит кайму по силуэту
        // и кладёт тени в кадр, а не от него. Тёплым ключ делает
        // та же атмосфера, что и всегда, — камера смотрит навстречу
        // солнцу и видит рассеяние вперёд; холодную тень даёт
        // поднятая карта окружения, то есть небо. Дымка урезана
        // вдвое с половиной: макет стоит на столе, и воздуха между
        // ним и глазом полметра.
        Look::Diorama => Scene {
            sun_elevation: 0.42,
            sun_azimuth: -2.44,
            ev100: 13.5,
            tonemap: Tonemap::Aces,
            grade: Grade {
                // Тёплым ключ делает атмосфера, и на контровом свете
                // она делает это **вдвое**: подкрашивать сверх неё
                // нечего. На 0.10 весь кадр становился одного оттенка,
                // и синяя сторона уезжала в фиолетовый.
                temperature: 0.0,
                tint: 0.01,
                post_saturation: 1.22,
                shadows: Section {
                    saturation: 1.18,
                    lift: 0.015,
                    ..Section::NEUTRAL
                },
                midtones: Section {
                    saturation: 1.04,
                    contrast: 1.05,
                    ..Section::NEUTRAL
                },
                highlights: Section {
                    saturation: 1.05,
                    gain: 1.02,
                    ..Section::NEUTRAL
                },
                ..Grade::NEUTRAL
            },
            vignette: Vignette {
                intensity: 0.70,
                radius: 0.70,
                smoothness: 0.50,
                roundness: 1.0,
                srgb: [0.0, 0.0, 0.0],
            },
            bloom: 0.20,
            // Десятая — не опечатка: см. `dof_f_stops`. На честных 2.8
            // кружок рассеяния выходил в сотую долю пикселя, то есть
            // ничего. Было 0.045 — и размыт был даже ближний строй:
            // резкость обязана стоять на предмете, а размываться —
            // дальний план (ADR-235).
            dof_f_stops: 0.12,
            sky_ibl: 2.0,
            haze_metres_per_voxel: 1.4,
            // Объёмного тумана нет намеренно (ADR-235): на плотности,
            // где он виден, макет тонет в бурой мути, а на плотности,
            // где мути нет, его не видно вовсе — воздух на снимках
            // референсов делает дымка по глубине, и она уже есть.
            ssao_thickness: 1.0,
            smaa: true,
            occlusion: Occl {
                radius: 6.0,
                strength: 0.6,
                bias: 0.15,
                power: 1.5,
            },
            ..base
        },

        // Графика. Солнце вдвое выше базового и сбоку: тень
        // становится **пятном определённой формы**, а не полосой
        // через весь кадр. Щелевое затенение выключено — оно мажет
        // угол мягким градиентом ровно там, где нужно чистое ребро.
        // Карта окружения поднята: тень обязана быть цветом,
        // а не темнотой. Дымка урезана почти вдвое: плоскому
        // затенению нужен плоский план.
        Look::Graphic => Scene {
            sun_elevation: 0.66,
            sun_azimuth: -0.95,
            ev100: 13.0,
            tonemap: Tonemap::Aces,
            grade: Grade {
                temperature: 0.02,
                post_saturation: 1.16,
                shadows: Section {
                    saturation: 1.10,
                    contrast: 1.45,
                    lift: 0.030,
                    ..Section::NEUTRAL
                },
                midtones: Section {
                    contrast: 1.30,
                    ..Section::NEUTRAL
                },
                // Насыщенность в светах — это небо: оно занимает верх
                // кадра и на плакате обязано быть цветом, а не бумагой.
                highlights: Section {
                    saturation: 1.30,
                    contrast: 1.10,
                    gamma: 0.92,
                    gain: 1.02,
                    ..Section::NEUTRAL
                },
                ..Grade::NEUTRAL
            },
            bloom: 0.06,
            sky_ibl: 1.9,
            haze_metres_per_voxel: 2.0,
            ssao: false,
            // Линия и ступени — то, ради чего направление и заведено.
            //
            // **Порог по нормали заведомо недостижим, и это решение,
            // а не отключение впрок.** У воксельного мира верх и бок
            // сходятся под прямым углом на каждом кубе: любой рабочий
            // порог по нормали обводит каждое ребро рельефа, и средний
            // план превращается в тёмную кашу. Силуэт даёт глубина,
            // а ребро воксела и так подчёркнуто плиткой.
            edge: Edge {
                strength: 0.92,
                width: 2.0,
                depth: 0.028,
                normal: 3.0,
                srgb: [0.06, 0.05, 0.09],
                steps: 4.0,
                posterise: 0.70,
            },
            ..base
        },

        // Техно. Холод, высокий контраст и дымка глубже базовой:
        // план за планом, и дальний край карты уходит в марево — это
        // и есть ощущение полигона. Насыщенность срезана на треть,
        // и цвет остаётся почти только у руды и огня.
        Look::Techno => Scene {
            // Солнце сбоку-сзади и невысоко: тень раскатывается
            // поперёк равнины и показывает её форму. Холод приходит
            // в кадр **после** расчёта: рассеяние красит свет
            // в тёплое, и врать источнику ради холода не надо.
            sun_elevation: 0.42,
            sun_azimuth: -1.70,
            ev100: 13.32,
            tonemap: Tonemap::AgX,
            grade: Grade {
                temperature: -0.07,
                // Положительный намеренно: отрицательный уводил кадр
                // в зелень, и вместе с рассеянием это давало бирюзу,
                // а не холод.
                tint: 0.01,
                post_saturation: 0.66,
                shadows: Section {
                    saturation: 0.85,
                    contrast: 1.30,
                    lift: 0.022,
                    ..Section::NEUTRAL
                },
                midtones: Section {
                    saturation: 0.95,
                    contrast: 1.30,
                    ..Section::NEUTRAL
                },
                highlights: Section {
                    saturation: 0.80,
                    contrast: 1.10,
                    gain: 0.92,
                    ..Section::NEUTRAL
                },
                ..Grade::NEUTRAL
            },
            vignette: Vignette {
                intensity: 0.50,
                radius: 0.85,
                smoothness: 0.60,
                roundness: 1.0,
                srgb: [0.0, 0.0, 0.0],
            },
            bloom: 0.12,
            sky_ibl: 1.70,
            haze_metres_per_voxel: 4.0,
            // Тонкая тёмная линия только по силуэту, без ступеней:
            // техно — направление про читаемость планов, а линия
            // отделяет план от плана там, где дымка их сблизила.
            edge: Edge {
                strength: 0.60,
                width: 1.0,
                depth: 0.022,
                // Недостижим по той же причине, что у графики: у куба
                // верх и бок сходятся под прямым углом.
                normal: 3.0,
                srgb: [0.04, 0.05, 0.07],
                steps: 0.0,
                posterise: 0.0,
            },
            ..base
        },

        // Вангеры. Солнце низкое и сбоку-сзади: склон против света
        // уходит в лиловое (`Surf::side`), освещённый — в охру, и рельеф
        // читается цветом, как в игре, откуда взято имя. Насыщенность
        // выше всех, тени цветные — карта окружения поднята. Резкость
        // везде: Вангеры — картинка сверху и без объектива.
        Look::Vangers => Scene {
            sun_elevation: 0.36,
            sun_azimuth: -1.85,
            ev100: 13.1,
            tonemap: Tonemap::Aces,
            grade: Grade {
                temperature: 0.02,
                tint: 0.01,
                post_saturation: 1.30,
                shadows: Section {
                    saturation: 1.25,
                    contrast: 1.10,
                    lift: 0.020,
                    ..Section::NEUTRAL
                },
                midtones: Section {
                    saturation: 1.05,
                    contrast: 1.08,
                    ..Section::NEUTRAL
                },
                highlights: Section {
                    saturation: 1.10,
                    gain: 1.02,
                    ..Section::NEUTRAL
                },
                ..Grade::NEUTRAL
            },
            vignette: Vignette {
                intensity: 0.35,
                radius: 0.85,
                smoothness: 0.60,
                roundness: 1.0,
                srgb: [0.02, 0.0, 0.04],
            },
            bloom: 0.12,
            sky_ibl: 2.1,
            haze_metres_per_voxel: 2.4,
            ssao_thickness: 1.0,
            smaa: true,
            occlusion: Occl {
                radius: 8.0,
                strength: 0.65,
                bias: 0.15,
                power: 1.6,
            },
            ..base
        },
    }
}

