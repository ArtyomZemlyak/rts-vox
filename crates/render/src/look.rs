    /// **Солнце нормировано и светит вниз — у каждого направления.**
    /// `looking_to` с ненормированным направлением кладёт масштаб
    /// в матрицу поворота света, а солнце из-под земли не освещает
    /// ничего — и то и другое видно только на картинке, то есть
    /// слишком поздно.
    #[test]
    fn the_sun_points_down_and_is_normalised() {
        let mut angles: Vec<(f32, f32)> = LOOK_ALL
            .iter()
            .map(|l| (scene_of(*l).sun_elevation, scene_of(*l).sun_azimuth))
            .collect();
        for e in [0.05f32, 0.33, 0.8, 1.4] {
            for a in [-2.0f32, -0.75, 0.0, 2.5] {
                angles.push((e, a));
            }
        }
        for (e, a) in angles {
            let d = sun_dir_at(e, a);
            let n = (d[0] * d[0] + d[1] * d[1] + d[2] * d[2]).sqrt();
            assert!((n - 1.0).abs() < 1e-5, "не нормирован: {n}");
            assert!(d[1] < 0.0, "солнце светит вверх при высоте {e}");
            // Высота восстанавливается из вектора: перепутанный
            // синус с косинусом проходит проверку на длину.
            assert!(((-d[1]).asin() - e).abs() < 1e-5);
        }
    }

    /// **Плитка фаски темнее у ребра и светлее в середине.** Знак здесь
    /// перепутать легко, а видно это только вблизи: перевёрнутая плитка
    /// даёт светлую решётку по швам вместо тени.
    #[test]
    fn the_chamfer_is_dark_at_the_edge() {
        for l in LOOK_ALL {
            let e0 = surf_of(l, Class::Rock).edge;
            let mid = chamfer_at(0.5, 0.5, e0);
            let edge = chamfer_at(0.0, 0.5, e0);
            let corner = chamfer_at(0.0, 0.0, e0);
            assert!(edge < mid, "ребро {edge} не темнее середины {mid}");
            assert!(corner <= edge + 1e-6, "угол светлее ребра");
            assert!((mid - 1.0).abs() < 1e-6, "середина не единица: {mid}");
            // Плитка обязана быть симметричной: иначе соседние воксели
            // сойдутся швом разной яркости.
            for (u, v) in [(0.2f32, 0.7f32), (0.05, 0.5), (0.31, 0.13)] {
                assert!((chamfer_at(u, v, e0) - chamfer_at(1.0 - u, v, e0)).abs() < 1e-6);
                assert!((chamfer_at(u, v, e0) - chamfer_at(v, u, e0)).abs() < 1e-6);
            }
        }
    }

    /// **Материалы различаются рисунком, а не только оттенком, —
    /// в каждом направлении.**
    ///
    /// Это весь смысл затеи: земля обязана читаться землёй, порода
    /// породой, руда рудой — при том, что цвет им всем даёт вершина,
    /// а плитка приходит серой. Пока плитка была одна на всех, любые
    /// две поверхности отличались только тем, чем их покрасили
    /// (ADR-211).
    #[test]
    fn the_three_materials_do_not_share_a_tile() {
        for l in LOOK_ALL {
            let tiles: Vec<Vec<u8>> = [Class::Soil, Class::Rock, Class::Ore]
                .map(|c| surface_tile_of(l, c).rgba)
                .into();
            for (i, a) in tiles.iter().enumerate() {
                for b in tiles.iter().skip(i + 1) {
                    let diff = a.iter().zip(b.iter()).filter(|(x, y)| x != y).count();
                    // Не «хоть чем-то»: рисунок должен расходиться
                    // на большей части плитки, иначе разницу съедят
                    // уровни детализации на первых же метрах.
                    assert!(
                        diff * 4 > a.len(),
                        "{}: две плитки совпадают на {}% пикселей",
                        look_name(l),
                        100 - diff * 100 / a.len()
                    );
                }
            }
            // И карты нормалей тоже: одинаковый рельеф при разном цвете —
            // это перекрашенный один материал, а не три.
            let soil = normal_tile_of(l, Class::Soil).rgba;
            let rock = normal_tile_of(l, Class::Rock).rgba;
            assert_ne!(
                soil,
                rock,
                "{}: у грунта и породы один рельеф",
                look_name(l)
            );
        }
    }

