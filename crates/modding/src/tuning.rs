//! Числа тика — в данных, а не в исходнике.
//!
//! `CLAUDE.md`: «любое игровое число (стоимость, HP, урон, скорость,
//! прочность материала, тайминг) живёт в `data/*.ron`, а не в
//! исходнике». Урон от падения, период перевыбора цели, потолки работы
//! за тик и рост юнита — всё это тайминг и баланс, и до ADR-140 они
//! лежали литералами в `World::new` и в аргументах `Ground::new`.
//!
//! Файл здесь **один на партию**, а не на пак: это не контент, который
//! мод добавляет, а правила, по которым идёт тик. Мод, меняющий их,
//! меняет игру для всех участников lockstep, и решаться это будет
//! отдельно.

use serde::Deserialize;

/// Вид ходовой. Перечисление в коде, числа — в данных: ровно так же
/// устроено оружие, где `WeaponKind` задаёт, **как** приходит урон,
/// а скорость и перезарядка лежат в файле (ADR-169, ADR-220).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ChassisKind {
    /// Гусеничная: разгоняется охотно, доворачивает тяжело,
    /// на подъёме вязнет.
    Tracked,
    /// Шагающая: разгоняется хуже, зато крутится на месте
    /// и лезет в гору.
    Walking,
}

impl ChassisKind {
    /// Номер для хеша. Вид переживает тик, значит входит в него
    /// (ADR-116).
    pub fn code(self) -> u8 {
        match self {
            ChassisKind::Tracked => 0,
            ChassisKind::Walking => 1,
        }
    }

    /// Обратно из номера. Нужно сохранению партии (ADR-229): вид
    /// ходовой пишется **номером**, а не местом в перечислении, ровно
    /// по той же причине, по которой номером пишется материал
    /// (ADR-028).
    ///
    /// Неизвестный номер — не `Tracked` по умолчанию, а `None`:
    /// молчаливая подмена ходовой это другая игра, а не другая
    /// картинка.
    pub fn from_code(c: u8) -> Option<ChassisKind> {
        match c {
            0 => Some(ChassisKind::Tracked),
            1 => Some(ChassisKind::Walking),
            _ => None,
        }
    }
}

/// Походка шагающей ходовой (ADR-234). У гусеничной её нет.
///
/// Фаза шага — состояние симуляции: от неё зависит, какая опора
/// поднята, а значит и наклон корпуса. Подъём ступни — только вид,
/// подвеска его не читает.
#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
pub struct Gait {
    /// Путь корпуса за полный цикл шага, сантиметры.
    pub stride_cm: i32,
    /// Доля цикла, которую ступня стоит на земле, проценты.
    pub duty_pct: i32,
    /// Высота переноса ступни, сантиметры.
    pub lift_cm: i32,
    /// Сдвиг фазы по опорам подвески, проценты цикла — в порядке
    /// опор: нос по `+Z`, нос по `−Z`, корма по `+Z`, корма по `−Z`.
    pub offset_pct: [i32; 4],
}

/// Пределы хода одной ходовой (ADR-220, ADR-234).
///
/// Всё — целые, потому что в данных живут целые: перевод в шаг за тик
/// делает тот, кто считает, а не тот, кто хранит (ADR-173).
///
/// **Тяга и масса вместо разгона.** Разгон и торможение выводятся
/// из тяги, тормозной силы и массы **машины**, а не задаются числом
/// на вид ходовой: крупная машина того же вида разгоняется
/// и поворачивает медленнее. Массу задаёт тело — объём на плотность;
/// без тела — номинал вида.
#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
pub struct Chassis {
    /// Номинальная масса машины вида, тонны: та, что у ванильного
    /// тела. Юнит без тела получает её.
    pub mass: i32,
    /// Средняя плотность машины, килограммов на кубометр: масса
    /// юнита — объём его тела на эту плотность.
    pub density: i32,
    /// Тяга, килоньютоны. Разгон — тяга на массу.
    pub thrust: i32,
    /// Тормозная сила, килоньютоны. Отдельно от тяги: машина
    /// останавливается быстрее, чем трогается.
    pub brake: i32,
    /// Предельная угловая скорость, градусов в секунду. Разгон к ней —
    /// из тяги на плече борта и момента инерции, отдельного числа нет.
    pub turn: i32,
    /// За каким углом до цели машина **сначала разворачивается**,
    /// а уже потом едет, в градусах. Больше прямого угла нарочно:
    /// поле направлений четырёхстороннее, и на диагонали курс
    /// отстаёт от него на полпрямого постоянно. Порог ровно в
    /// девяносто превратил бы диагональ в череду остановок.
    pub pivot: i32,
    /// Доля предельной скорости в развороте за порогом, процентов.
    /// Ноль — разворот на месте; больше нуля — машина идёт дугой.
    pub pivot_speed: i32,
    /// Доля предельной скорости на подъёме, процентов.
    pub climb: i32,
    /// Доля предельной скорости на спуске, процентов. Больше ста —
    /// под гору катится быстрее, чем по ровному.
    pub descend: i32,

    // --- подвеска (ADR-225)
    //
    // Корпус — твёрдое тело на пружинах в точках опоры, и наклон
    // машины выходит из сил, а не из нормали клетки. Размеры здесь
    // в **сантиметрах**: это размеры машины, а машина меряется
    // в метрах, не в вокселях.
    /// Жёсткость подвески, отнесённая к массе: ускорение на мировую
    /// единицу сжатия.
    pub stiffness: i32,
    /// Демпфирование, отнесённое к массе.
    pub damping: i32,
    /// Ход подвески, сантиметры.
    pub travel_cm: i32,
    /// Клиренс: насколько центр корпуса выше опоры в покое, сантиметры.
    pub clearance_cm: i32,
    /// Момент инерции, отнесённый к массе, — квадрат радиуса инерции
    /// в мировых единицах. Больше — корпус ленивее качается.
    pub inertia: i32,
    /// Угловое трение. Без него корпус качается вечно: подвеска гасит
    /// подъём, но не вращение вокруг центра масс.
    pub ang_damp: i32,
    /// Опора от центра к носу и к корме, сантиметры.
    pub support_x_cm: i32,
    /// Опора от центра к борту, сантиметры.
    pub support_z_cm: i32,
    /// Предел завала: наименьшее `up.y` в процентах. Сто — корпус
    /// всегда горизонтален, восемьдесят семь — около тридцати
    /// градусов.
    pub max_tilt_pct: i32,
    /// Походка: есть у шагающей, нет у гусеничной (ADR-234).
    pub gait: Option<Gait>,
}

/// Bounded gameplay blast field; envelope strength is distinct from joules.
#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
pub struct Blast {
    pub cell: u32,
    pub samples_per_tick: u32,
    pub wave_pops_per_tick: u32,
    pub edits_per_tick: u32,
    pub max_pending: u32,
    pub max_claims: u32,
    pub max_fragments: u32,
    pub max_flying: u32,
    pub pile_cell: u32,
    pub resistance_per_strength: u32,
    pub fracture_kj_m3_per_strength: u32,
    pub density_kg_m3_per_density: u32,
    pub motion_pct: u32,
    pub body_energy_pct: u32,
    pub body_resistance_ppm: u32,
    pub lift_pct: u32,
    pub max_speed_mm_s: u32,
    pub drag_pct: u32,
    pub bounce_pct: u32,
    pub friction_pct: u32,
    pub sleep_mm_s: u32,
}

#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
pub struct Impact {
    pub detach_work_per_tick: u32,
    pub detach_jobs_per_tick: u32,
    /// Armour, core, engine, weapon, sensor. Work density in kJ/m³.
    pub work_kj_m3: [u32; 5],
    pub motion_pct: u32,
    pub cells_per_tick: u32,
    pub jobs_per_tick: u32,
    pub max_pending: u32,
}

/// Настройки тика. Полями обязаны быть заполнены все: `serde` без
/// `default` не простит пропуска, и это нарочно — забытое поле
/// не должно молча стать нулём.
#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
pub struct Tuning {
    /// Material penetration and queue budgets for real unit volumes.
    pub impact: Impact,
    pub blast: Blast,
    /// Урона за воксель высоты падения (ADR-036). Первый воксель
    /// бесплатен — это правило, а не число, и живёт в коде (ADR-139).
    pub fall_damage_per_voxel: u16,
    /// Ускорение свободного падения, вокселей в секунду за секунду.
    ///
    /// **Мировая константа, а не свойство оружия или тела** (ADR-173):
    /// одно тяготение на юнита, обломок и снаряд. Разные числа
    /// означали бы, что юнит и кусок, отвалившиеся вместе,
    /// разъезжаются в воздухе.
    ///
    /// В ускорение за тик переводит тот, кто считает: `Fx::from_ratio`
    /// на квадрат частоты тика. Хранить сразу за тик нельзя —
    /// это дробь, а в данных живёт целое.
    pub gravity: i32,
    /// Через сколько тиков юнит пересматривает живую цель. Ноль —
    /// пересматривать каждый тик.
    ///
    /// Секунда выбрана так, чтобы потолок поисков в обычном бою
    /// **не срабатывал**: потолок, упирающийся каждый тик, — это
    /// не предохранитель, а постоянное ухудшение (ADR-116).
    pub retarget_period: u32,
    /// Потолок поисков цели за тик. Второй потолок того же рода, что
    /// у дренажа мира: работа, которой в плотном бою становится
    /// квадратично много, обязана быть ограничена (ADR-114, ADR-116).
    pub max_target_searches: usize,
    /// Потолки работы над полем направлений за тик (ADR-138): клеток
    /// на сборку графа, узлов на просмотр, годуновских обновлений
    /// на развёртку.
    ///
    /// Целиком поле D-7 считается сорок миллисекунд — вчетверо больше
    /// всего тика, — поэтому расчёт идёт порциями и продолжается
    /// со следующего тика. Потолок фиксирован, а не «сколько успеем»:
    /// разное отставание у разных клиентов это десинк (ADR-089).
    pub flow_cells_per_tick: u32,
    pub flow_scan_per_tick: u32,
    /// Секторов на пересборку графа секторов и на решение поля.
    ///
    /// Потолка на **годуновские обновления** здесь нет намеренно.
    /// Он был, не читался никем и сработать не мог: поле делает около
    /// 127 обновлений за тик при объявленных двенадцати тысячах.
    /// Работу ограничивает потолок секторов, а второй, не срабатывающий
    /// никогда, — не предохранитель, а число, которое кто-то однажды
    /// примет за действующее правило (ADR-190).
    pub flow_sectors_per_tick: u32,
    /// Потолок приказов, применяемых за тик (ADR-195).
    ///
    /// Третий потолок того же рода, что у дренажа правок и у поиска
    /// цели: упёршийся приказ откладывается на следующий тик, а не
    /// теряется и не останавливает очередь (ADR-114).
    pub max_orders_per_tick: usize,
    /// Насколько близко к точке приказа юнит считает, что дошёл,
    /// в мировых единицах.
    ///
    /// Обязан быть больше радиуса расталкивания: толпа, идущая
    /// в одну точку, не встаёт ближе, чем расходятся её соседи.
    pub order_arrive: i32,
    /// Fractions of equipped weapon range: enter / leave the firing stop.
    pub engagement_pct: [u32; 2],
    /// Радиус шара породы, снимаемого копателем за тик, в вокселях.
    pub dig_radius: i32,

    // --- экономика (ADR-230)
    //
    /// Потолок запаса стороны без единого склада, единиц материи
    /// (ADR-043). Ноль означал бы, что до первого склада выкопанное
    /// некуда положить, то есть партию нельзя начать.
    pub base_store: u64,
    /// Насколько близко юнит должен быть к складу, недострою или
    /// обломку, чтобы работать, в мировых единицах.
    ///
    /// Отдельно от `order_arrive`: постройка крупная, и подъезжать
    /// к её середине вплотную юнит не обязан.
    pub work_reach: i32,
    /// Выход переработки на складе: `refine_num / refine_den`.
    ///
    /// **Единственный сток, доступный с первого дня**
    /// (`docs/07-economy.md`), и он обязан быть включён с самого
    /// начала: сохраняющая экономика без стока не заканчивается.
    /// Числитель меньше знаменателя — иначе стока нет.
    pub refine_num: u64,
    pub refine_den: u64,
    /// Доля содержимого, теряемая при разрушении контейнера (ADR-021):
    /// `breach_loss_num / breach_loss_den`.
    pub breach_loss_num: u64,
    pub breach_loss_den: u64,
    /// Потолок поисков склада **и обломка** за тик.
    ///
    /// И там, и там копатель ищет, к чему приткнуться, и число пар
    /// «копатель × постройка» либо «копатель × обломок» в плотном
    /// случае растёт квадратично (ADR-114). Бюджет один на оба:
    /// два потолка на одну работу — это два числа, которые однажды
    /// разойдутся.
    ///
    /// Упёршийся поиск **откладывается** на следующий тик: краулер
    /// ждёт тик, а не теряет груз, и обломок никуда не денется.
    pub max_dock_searches: u32,
    /// Сколько заказов держит очередь одного завода. Очередь без
    /// потолка — это способ занять память приказами.
    pub max_build_queue: usize,
    /// Рост юнита в вокселях: столько нужно свободного над полом.
    pub unit_height: u32,
    /// Сторона нав-клетки в вокселях (ADR-014).
    pub nav_cell: u32,
    /// Какой перепад юнит перешагивает; больше — обрыв, ребра нет
    /// (ADR-121).
    pub max_step: u32,
    /// Потолок правок мира за тик — `MAX_VOXEL_EDITS_PER_TICK` канона
    /// (ADR-013, ADR-045). Считает **затронутые воксели**, в любом
    /// масштабе, и столько же записей очереди разрешает просмотреть
    /// (ADR-182).
    ///
    /// Это число тика, а не мира: жило литералом `1 << 16` в сборке
    /// эталонного сценария и в каждой сцене своим, то есть было
    /// вторым источником правды рядом с соседними потолками (ADR-227).
    /// Выбирается так, чтобы на эталонном сценарии **не срабатывать**:
    /// потолок, упирающийся каждый тик, — не предохранитель,
    /// а постоянное ухудшение (ADR-114, ADR-116).
    pub max_voxel_edits_per_tick: u32,
    /// Чанков, построенных из генератора за тик (ADR-114).
    ///
    /// Второй потолок дренажа очереди правок: без него тик, в котором
    /// забой вошёл в шестнадцать нетронутых чанков разом, стоит
    /// тридцать четыре миллисекунды. Жил в исходнике `voxel`,
    /// хотя это число тика, как и соседние (ADR-191).
    pub max_materialize_per_tick: u32,
    /// Потолок на размер одного отвала в вокселях (ADR-119).
    ///
    /// Больше — не тело, а событие другого масштаба, и оно остаётся
    /// в мире. Канон называет это число (`docs/14-demo-scenes.md`),
    /// а `Tuning` его не знал (ADR-191).
    pub max_body_cells: u32,
    /// Жёсткий потолок живых динамических тел (ADR-015).
    pub max_bodies: usize,
    /// Радиус расталкивания: ближе этого юниты расходятся.
    pub separation: i32,
    /// Дальность стрельбы в мировых единицах.
    pub range: i32,
    /// Потолок на снаряды в воздухе. Работа за тик линейна по ним,
    /// и без потолка залп пяти тысяч юнитов кладёт тик.
    ///
    /// Числа **самого оружия** — скорость, урон, перезарядка, воронка —
    /// живут не здесь, а в `data/weapons.ron` (ADR-169): они у каждого
    /// вида свои, а это — общий потолок на всех.
    pub max_shots: usize,
    /// Радиус попадания, клеток: снаряд попал, если цель ближе.
    pub shot_hit_radius: i32,
    /// Пределы хода гусеничной машины (ADR-220).
    pub tracked: Chassis,
    /// Пределы хода шагающей машины.
    pub walking: Chassis,
}

#[derive(Debug)]
pub enum TuningError {
    Ron(String),
    Io(String),
}

impl std::fmt::Display for TuningError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            TuningError::Ron(e) => write!(f, "разбор RON: {e}"),
            TuningError::Io(e) => write!(f, "чтение файла: {e}"),
        }
    }
}

impl Tuning {
    /// Разобрать из текста. Без ввода-вывода — этим пользуется и тест,
    /// и загрузчик.
    pub fn from_ron(s: &str) -> Result<Tuning, TuningError> {
        let t: Tuning = ron::from_str(s).map_err(|e| TuningError::Ron(e.to_string()))?;
        if t.engagement_pct[0] == 0
            || t.engagement_pct[0] >= t.engagement_pct[1]
            || t.engagement_pct[1] > 100
        {
            return Err(TuningError::Ron("invalid engagement range band".into()));
        }
        if t.impact.cells_per_tick == 0
            || t.impact.jobs_per_tick == 0
            || t.impact.max_pending == 0
            || t.impact.detach_work_per_tick == 0
            || t.impact.detach_jobs_per_tick == 0
            || t.impact.motion_pct >= 100
            || t.impact.work_kj_m3.contains(&0)
        {
            return Err(TuningError::Ron(
                "impact work and budgets must be positive".into(),
            ));
        }
        let b = &t.blast;
        if !(1..=4).contains(&b.cell)
            || b.samples_per_tick == 0
            || b.wave_pops_per_tick == 0
            || b.edits_per_tick == 0
            || b.max_pending == 0
            || b.max_pending > 64
            || b.max_claims == 0
            || b.max_fragments == 0
            || b.max_flying == 0
            || b.max_flying > b.max_fragments
            || b.pile_cell == 0
            || b.resistance_per_strength == 0
            || b.fracture_kj_m3_per_strength == 0
            || b.density_kg_m3_per_density == 0
            || b.body_energy_pct > 100
            || b.body_resistance_ppm == 0
            || b.motion_pct >= 100
            || b.lift_pct > 100
            || b.max_speed_mm_s == 0
            || b.max_speed_mm_s > 120000
            || b.drag_pct > 100
            || b.bounce_pct >= 100
            || b.friction_pct > 100
            || b.sleep_mm_s == 0
        {
            return Err(TuningError::Ron(
                "invalid blast domain, energy or work budgets".into(),
            ));
        }
        Ok(t)
    }

    /// Пределы хода по виду ходовой.
    pub fn chassis(&self, k: ChassisKind) -> &Chassis {
        match k {
            ChassisKind::Tracked => &self.tracked,
            ChassisKind::Walking => &self.walking,
        }
    }
}

/// Прочитать файл настроек тика.
pub fn load_tuning(path: &std::path::Path) -> Result<Tuning, TuningError> {
    let s = std::fs::read_to_string(path).map_err(|e| TuningError::Io(e.to_string()))?;
    Tuning::from_ron(&s)
}

