//! Канал приказов: единственный способ повлиять на симуляцию снаружи.
//!
//! `docs/02-architecture.md` объявляет его контрактом слоя: «Ввод игрока
//! не меняет состояние напрямую — он превращается в **команду**, команда
//! попадает в очередь на тик N+delay, и только симуляция её применяет».
//! У мода правило то же (`docs/09-modding.md`): «нет прямых мутаторов…
//! он ставит запросы в те же отложенные очереди, что и ядро».
//!
//! Отсюда устройство: приказ — это **данные**, которые кладут в очередь
//! мира, и применяет их фаза `ApplyCommands`. Ни рендер, ни мод не пишут
//! в состояние сами (ADR-195).
//!
//! Координаты целые. Приказ входит в состояние симуляции, а плавающего
//! в ней нет (`CLAUDE.md`); перевод пикселя в мировую единицу — забота
//! того, кто щёлкает мышью, и делается он до постановки в очередь.

/// Юнит идёт по полю направлений своей стороны — то, что он делает
/// **без приказа**. Ноль нарочно: свежий слот начинается с него.
pub const STANCE_FLOW: u8 = 0;
/// Юнит идёт в точку приказа и остаётся при ней.
pub const STANCE_MOVE: u8 = 1;
/// Юнит стоит на месте.
pub const STANCE_HOLD: u8 = 2;
/// Юнит идёт к забою и грызёт его.
pub const STANCE_DIG: u8 = 3;

/// Приказ юниту.
///
/// Перечисление, а не набор полей: приказ едет по сети и пишется
/// в реплей целиком, и «половина приказа» не должна быть выразима.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Order {
    /// Идти в точку и остаться при ней.
    MoveTo { unit: u32, x: i32, z: i32 },
    /// Стоять на месте. Отмена любого другого приказа.
    Hold { unit: u32 },
    /// Вернуться под поле своей стороны — снять приказ вовсе.
    Release { unit: u32 },
    /// Атаковать названного юнита: держать его целью и идти к нему.
    Attack { unit: u32, target: u32 },
    /// Копать шахту от названного воксела вниз.
    Dig { unit: u32, x: i32, y: i32, z: i32 },
}

impl Order {
    /// Кому приказ. Проверка «жив ли адресат» одна на все виды,
    /// и делать её разбором по виду значило бы пять раз одно и то же.
    pub fn unit(self) -> u32 {
        match self {
            Order::MoveTo { unit, .. }
            | Order::Hold { unit }
            | Order::Release { unit }
            | Order::Attack { unit, .. }
            | Order::Dig { unit, .. } => unit,
        }
    }
}

/// Скорость юнита к точке приказа, мировых единиц в секунду по осям.
///
/// **Не четырьмя направлениями**, как поле. Поле живёт на сетке
/// нав-клеток, и четырёх ему хватает; точка приказа на сетке не живёт,
/// и лестница из четырёх направлений читается как «юнит идёт не туда».
///
/// Нормировка — делением на большую координату: целое деление, без
/// корня. «Внутри радиуса ли» решается сравнением **квадратов**
/// (ADR-071), и здесь это тот же приём.
///
/// Дойдя, юнит останавливается, но приказа не теряет: расталкивание
/// соседей продолжает работать, и вытолкнутый из точки возвращается
/// к ней сам.
#[inline]
pub fn goal_velocity(ux: i32, uz: i32, gx: i32, gz: i32, speed: i32, arrive: i32) -> (i32, i32) {
    let (dx, dz) = (gx - ux, gz - uz);
    if dx * dx + dz * dz <= arrive * arrive {
        return (0, 0);
    }
    let m = dx.abs().max(dz.abs()).max(1);
    (dx * speed / m, dz * speed / m)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Дошедший стоит, недошедший идёт, и идёт он **в ту сторону**.
    #[test]
    fn the_goal_velocity_points_at_the_goal_and_stops_on_arrival() {
        assert_eq!(goal_velocity(0, 0, 3, 4, 6, 16), (0, 0), "внутри радиуса — стоять");
        let (vx, vz) = goal_velocity(0, 0, 100, 0, 6, 16);
        assert_eq!((vx, vz), (6, 0));
        let (vx, vz) = goal_velocity(0, 0, -100, -100, 6, 16);
        assert_eq!((vx, vz), (-6, -6), "по диагонали идут обе оси");
        let (vx, vz) = goal_velocity(0, 0, 100, 50, 6, 16);
        assert!(vx > 0 && vz > 0 && vx > vz, "вышло {vx},{vz}");
    }

    /// Нулевая скорость никуда не уводит, и деления на ноль нет.
    #[test]
    fn a_goal_under_the_feet_never_divides_by_zero() {
        assert_eq!(goal_velocity(7, 7, 7, 7, 6, 0), (0, 0));
    }
}
